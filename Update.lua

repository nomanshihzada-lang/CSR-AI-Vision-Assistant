-- =====================================================================
-- ہلکا پھلکا TTS انجن — صرف رفتار (rate) اور پچ (pitch) کنٹرول کرنے کے
-- لیے۔ نوٹ: یہ جان بوجھ کر زبان/لوکیل (language/locale) کو کبھی تبدیل
-- نہیں کرتا — وہی مسئلہ تھا جو پہلے آواز کے کام نہ کرنے کا سبب بنا۔
-- ڈیوائس کی موجودہ ڈیفالٹ آواز پر ہی رفتار/پچ لگائی جاتی ہے۔ اگر یہ
-- انجن کسی وجہ سے تیار نہ ہو تو خودکار طور پر service.speak() پر واپس
-- چلا جاتا ہے (کریش نہیں ہوتا)۔
-- =====================================================================
local rateTtsEngine = nil
local rateTtsReady = false
local rateTtsConfiguredKey = nil  -- انجن پیکج+آواز کا کومبی نیشن جس کے ساتھ موجودہ انسٹینس بنا

-- ایک کنفیگرڈ TTS انجن تیار کرتا ہے: منتخب انجن (Settings > TTS Settings
-- سے)، منتخب آواز، اور رفتار/پچ کے ساتھ۔ اگر کچھ سیٹ نہ ہو تو ڈیوائس کا
-- ڈیفالٹ انجن/آواز استعمال ہوتی ہے۔
function ensureRateTTSReady(callback)
    local enginePkg = getTTSEnginePackage()
    local voiceName = getTTSVoiceName()
    local configKey = (enginePkg or "") .. "|" .. (voiceName or "")

    if rateTtsEngine and rateTtsReady and rateTtsConfiguredKey == configKey then
        callback(true)
        return
    end

    -- اگر انجن پہلے سے موجود ہے مگر ترتیب بدل گئی ہے تو پرانا بند کر کے نیا بنائیں
    if rateTtsEngine and rateTtsConfiguredKey ~= configKey then
        pcall(function() rateTtsEngine.shutdown() end)
        rateTtsEngine = nil
        rateTtsReady = false
    end

    local function applyVoiceAndReturn()
        if voiceName and voiceName ~= "" then
            pcall(function()
                local voices = rateTtsEngine.getVoices()
                if voices then
                    local iterator = voices.iterator()
                    while iterator.hasNext() do
                        local v = iterator.next()
                        if tostring(v.getName()) == voiceName then
                            rateTtsEngine.setVoice(v)
                            break
                        end
                    end
                end
            end)
        end
        rateTtsConfiguredKey = configKey
        rateTtsReady = true
        callback(true)
    end

    local ok, err = pcall(function()
        local initListener = TextToSpeech.OnInitListener{
            onInit = function(status)
                if status == TextToSpeech.SUCCESS then
                    applyVoiceAndReturn()
                else
                    logWarn("Rate-control TTS init failed, status=" .. tostring(status))
                    rateTtsReady = false
                    callback(false)
                end
            end
        }
        if enginePkg and enginePkg ~= "" then
            rateTtsEngine = TextToSpeech(ctx, initListener, enginePkg)
        else
            rateTtsEngine = TextToSpeech(ctx, initListener)
        end
    end)
    if not ok then
        logError("Rate-control TTS creation failed: " .. tostring(err))
        callback(false)
    end
end

-- موجودہ منتخب زبان میں متن بولتا ہے — بغیر کسی الگ وائس ڈیٹا انسٹال
-- کیے، وہی طریقہ استعمال کرتے ہوئے جو باقی پوری ایپ میں کام کر رہا ہے۔
-- اگر صارف نے TTS Settings میں انجن/آواز/رفتار/پچ میں سے کچھ بھی
-- ڈیفالٹ سے تبدیل کیا ہو تو کنفیگرڈ TTS انجن سے بولا جاتا ہے، ورنہ
-- عام service.speak() ہی استعمال ہوتا ہے۔
function speakInSelectedLanguage(text)
    if not text or text == "" then return end

    local rate = getSpeechRate()
    local pitch = getSpeechPitch()
    local enginePkg = getTTSEnginePackage()
    local voiceName = getTTSVoiceName()
    local needsCustomTTS = (rate ~= 1.0) or (pitch ~= 1.0) or (enginePkg ~= "") or (voiceName ~= "")

    local function speakViaServiceFallback()
        local ok, err = pcall(function()
            if service and service.speak then
                service.speak(text)
            end
        end)
        if not ok then
            logError("speakInSelectedLanguage: service.speak failed: " .. tostring(err))
        end
    end

    if needsCustomTTS then
        ensureRateTTSReady(function(ready)
            if ready and rateTtsEngine then
                local ok, err = pcall(function()
                    rateTtsEngine.setSpeechRate(rate)
                    rateTtsEngine.setPitch(pitch)
                    rateTtsEngine.speak(text, TextToSpeech.QUEUE_FLUSH, nil, "csr_live_utterance")
                end)
                if not ok then
                    logError("Rate-control TTS speak failed, falling back: " .. tostring(err))
                    speakViaServiceFallback()
                end
            else
                speakViaServiceFallback()
            end
        end)
    else
        speakViaServiceFallback()
    end

    -- طویل جواب اسکرین پر بھی دکھا دیں (تاکہ سکرین ریڈر یا خود صارف اسے پڑھ/دیکھ سکے)
    pcall(function()
        Toast.makeText(ctx, text, Toast.LENGTH_LONG).show()
    end)
end

function stopTTS()
    if rateTtsEngine then
        pcall(function()
            rateTtsEngine.stop()
        end)
    end
end

