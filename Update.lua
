-- Safe Mode: لگاتار ناکامیوں کے بعد فیچر کو عارضی بند کرنا تاکہ ایپ کریش نہ ہو
-- اور یوزر کو واضح پیغام ملے۔ کامیاب کال پر کاؤنٹر خودکار ری سیٹ ہو جاتا ہے۔
function enterSafeModeIfNeeded()
    runtimeState.consecutiveFailures = runtimeState.consecutiveFailures + 1
    logWarn("Consecutive failure count: " .. runtimeState.consecutiveFailures)
    if runtimeState.consecutiveFailures >= CONFIG.SAFE_MODE_FAILURE_THRESHOLD and not runtimeState.safeModeActive then
        runtimeState.safeModeActive = true
        logError("SAFE MODE ACTIVATED after " .. runtimeState.consecutiveFailures .. " consecutive failures.")
        notify("Safe Mode فعال: بار بار ایرر آنے کی وجہ سے AI فیچر عارضی طور پر روکا گیا۔ Settings چیک کریں۔")
    end
end

function resetFailureState()
    if runtimeState.consecutiveFailures > 0 or runtimeState.safeModeActive then
        logInfo("API call succeeded — resetting failure counter / leaving Safe Mode.")
    end
    runtimeState.consecutiveFailures = 0
    runtimeState.safeModeActive = false
end

-- اندرونی: ایک ہی کوشش (attempt) کے لیے HTTP کال
local function attemptGeminiCall(url, payload, attemptNumber, model, onDone)
    local ok, err = pcall(function()
        Http.post(url, cjson.encode(payload), { ["Content-Type"] = "application/json" }, function(status, data)
            if status == 200 then
                local decodeOk, decoded = pcall(cjson.decode, data)
                if decodeOk and decoded and decoded.candidates and decoded.candidates[1] then
                    local content = decoded.candidates[1].content
                    if content and content.parts and content.parts[1] then
                        onDone(content.parts[1].text, nil, false)
                    else
                        onDone(nil, "No text found in the image, or the API blocked the response (safety filters).", false)
                    end
                else
                    onDone(nil, "Invalid / corrupt API response. The model might be temporarily unstable.", true)
                end
            elseif status == 404 then
                -- غلط یا نان-ایگزسٹنٹ ماڈل آئی ڈی — دوبارہ کوشش کرنے کا فائدہ نہیں
                onDone(nil, "Error 404: The selected model (" .. model .. ") is not available for your API key/region.", false)
            elseif status == 429 then
                onDone(nil, "Error 429: Rate limit / quota exceeded.", true)
            elseif status >= 500 then
                onDone(nil, "Server Error " .. status .. ": Gemini service temporarily unavailable.", true)
            else
                onDone(nil, "API Error: " .. status, false)
            end
        end)
    end)
    if not ok then
        logError("attemptGeminiCall pcall failed: " .. tostring(err))
        onDone(nil, "Network/Runtime error while calling API: " .. tostring(err), true)
    end
end

-- عوامی فنکشن: خودکار ری-ٹرائی اور Safe Mode کے ساتھ Gemini کو امیج بھیجنا
function callGeminiWithImage(apiKey, model, base64Data, prompt, callback)
    if runtimeState.safeModeActive then
        logWarn("callGeminiWithImage blocked: Safe Mode is active.")
        callback(nil, "Safe Mode فعال ہے۔ بار بار ایرر کی وجہ سے AI عارضی طور پر بند ہے۔ کچھ دیر بعد یا Settings چیک کر کے دوبارہ کوشش کریں.")
        return
    end

    local modelInfo = geminiApiDetails[model]
    if not modelInfo then
        logError("callGeminiWithImage: invalid model '" .. tostring(model) .. "'")
        callback(nil, "Invalid model selected")
        return
    end
    local url = "https://generativelanguage.googleapis.com/" .. modelInfo.version .. "/" .. modelInfo.id .. ":generateContent?key=" .. apiKey
    local payload = {
        contents = {{
            parts = {
                { text = prompt },
                { inlineData = { mimeType = "image/jpeg", data = base64Data } }
            }
        }}
    }

    logInfo("Calling Gemini model=" .. model .. " url=" .. modelInfo.version .. "/" .. modelInfo.id)

    local function tryAttempt(attemptNumber)
        attemptGeminiCall(url, payload, attemptNumber, model, function(result, errMsg, retryable)
            if result then
                logInfo("Gemini call succeeded on attempt " .. attemptNumber)
                resetFailureState()
                callback(result, nil)
                return
            end

            logError("Gemini call failed (attempt " .. attemptNumber .. "): " .. tostring(errMsg))

            if retryable and attemptNumber <= CONFIG.MAX_RETRIES then
                local handler = Handler(Looper.getMainLooper())
                handler.postDelayed(Runnable({ run = function()
                    tryAttempt(attemptNumber + 1)
                end }), CONFIG.RETRY_DELAY_MS)
            else
                enterSafeModeIfNeeded()
                callback(nil, errMsg)
            end
        end)
    end

    tryAttempt(1)
end

