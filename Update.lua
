    local savedDay = aiPrefs.getString("tokens_day_date", "")
    local dayTotal = (savedDay == today) and aiPrefs.getInt("tokens_day_total", 0) or 0

    local savedMonth = aiPrefs.getString("tokens_month_str", "")
    local monthTotal = (savedMonth == month) and aiPrefs.getInt("tokens_month_total", 0) or 0

