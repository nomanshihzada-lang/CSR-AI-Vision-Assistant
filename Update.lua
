-- ایپ کھلتے ہی منتخب ڈیفالٹ موڈ کھولتا ہے؛ کامیاب ہو تو true
function launchDefaultMode()
    local mode = getDefaultMode()
    if not mode or mode == "" or mode == "None" then return false end
    local actions = {
        ["Live Mode"] = function() startLiveMode({ kind = "live" }) end,
        ["Camera Mode"] = function() startLiveMode({ kind = "camera" }) end,
        ["Find Object"] = function() showFindObjectDialog() end,
        ["Document Reader"] = function() startLiveMode({ kind = "document" }) end,
        ["Voice Message to Text"] = function() showVoiceToTextDialog() end,
        ["Light Detector"] = function() runLightDetector(true) end
    }
    local action = actions[mode]
    if not action then return false end
    logInfo("Opening default mode: " .. tostring(mode))
    action()
    return true
end

