local liveModeState = {
    active = false,
    camera = nil,
    busy = false,
    lastFrameBase64 = nil   -- سب سے تازہ فریم — Voice Q&A کے لیے سیاق و سباق کے طور پر استعمال ہوگا
}

function stopLiveMode()
    liveModeState.active = false
    if liveModeState.camera then
        pcall(function()
            liveModeState.camera.setPreviewCallback(nil)
            liveModeState.camera.stopPreview()
            liveModeState.camera.release()
        end)
        liveModeState.camera = nil
    end
    stopTTS()
    logInfo("Live Mode stopped.")
end

function nv21ToJpegBase64(data, camera)
    local ok, result = pcall(function()
        local params = camera.getParameters()
        local size = params.getPreviewSize()
        local yuvImage = YuvImage(data, ImageFormat.NV21, size.width, size.height, nil)
        local out = ByteArrayOutputStream()
        local rect = Rect(0, 0, size.width, size.height)
        yuvImage.compressToJpeg(rect, CONFIG.JPEG_QUALITY, out)
        local bytes = out.toByteArray()
        out.close()
        return Base64.encodeToString(bytes, Base64.NO_WRAP)
    end)
    if ok then return result end
    logError("nv21ToJpegBase64 failed: " .. tostring(result))
    return nil
end

function processLiveFrame(base64Data, statusTv)
    liveModeState.lastFrameBase64 = base64Data  -- Voice Q&A کے لیے تازہ فریم محفوظ رکھیں

    local apiKey = getGeminiApiKey()
    if not apiKey or apiKey == "" then
        if statusTv then statusTv.setText("API Key missing — open Settings first.") end
        return
    end
    liveModeState.busy = true
    vibratePattern("processing")
    local lang = getSelectedLanguage()
    local prompt = "Reply in exactly ONE short, natural, spoken-style sentence (max 12 words). Describe anything important directly ahead for a visually impaired person walking: people, obstacles, stairs, vehicles, doors, or hazards. If the path is clear, say so — in " .. lang .. ". IMPORTANT: your entire reply must be written ONLY in " .. lang .. ". Do not use English or any other language, not even a single word (unless " .. lang .. " itself is English). Do not add labels, quotes, or any extra text — output only the spoken sentence."
    callGeminiWithImage(apiKey, getGeminiModel(), base64Data, prompt, function(res, err)
        liveModeState.busy = false
        if res then
            if statusTv then pcall(function() statusTv.setText(res) end) end
            speakInSelectedLanguage(res)
            saveHistoryEntry("Live Mode (" .. lang .. ")", res)
        else
            logError("Live frame error: " .. tostring(err))
        end
    end)
end

-- =====================================================================
-- VOICE Q&A (Live Mode کے دوران) — "Press & Ask" طرز
--
-- نوٹ: یہ ایک اصلی مسلسل/live فون کال جیسی گفتگو نہیں ہے (وہ Gemini کے
-- الگ streaming/WebSocket-based Live API کے بغیر اس REST سیٹ اپ میں
-- قابلِ اعتماد طریقے سے نہیں بن سکتی)۔ بجائے اس کے، یہ "دبائیں اور
-- پوچھیں" طرز کا نظام ہے: بٹن دبائیں → سوال بولیں → موجودہ کیمرہ فریم
-- کے سیاق و سباق کے ساتھ Gemini سے مختصر جواب → جواب بولا جاتا ہے۔
--
-- RECORD_AUDIO پرمیشن ایپ کے پاس ہونی چاہیے (کیمرہ پرمیشن جیسا مسئلہ
-- ہو سکتا ہے)۔ ناکامی کی صورت میں واضح پیغام ملے گا، کریش نہیں ہوگا۔
-- =====================================================================
function askGeminiFollowUp(question, statusTv)
    local apiKey = getGeminiApiKey()
    if not apiKey or apiKey == "" then
        notify("API Key missing! پہلے Settings میں سیٹ کریں")
        return
    end
    if not liveModeState.lastFrameBase64 then
        notify("ابھی کوئی کیمرہ فریم دستیاب نہیں، چند سیکنڈ بعد دوبارہ کوشش کریں")
        return
    end

    vibratePattern("processing")
    local lang = getSelectedLanguage()
    local prompt = "You are a helpful, knowledgeable voice assistant for a visually impaired user, talking with them by voice. They just asked, by voice: \"" .. question .. "\". " ..
        "If their question relates to what is currently visible in the attached camera image, use the image to answer accurately. " ..
        "If it is a general question unrelated to the image (facts, advice, explanations, calculations, definitions, translations, how-to help, conversation, or anything else), just answer it directly and helpfully like a normal AI assistant would — do not force a connection to the image. " ..
        "Give a clear, complete, natural-sounding spoken answer (a few sentences if needed, as long as it fully answers the question). " ..
        "IMPORTANT: your entire reply must be written ONLY in " .. lang .. ". Do not use English or any other language, not even a single word, unless " .. lang .. " itself is English."

    callGeminiWithImage(apiKey, getGeminiModel(), liveModeState.lastFrameBase64, prompt, function(res, err)
        if res then
            if statusTv then pcall(function() statusTv.setText("Q: " .. question .. "\n\nA: " .. res) end) end
            speakInSelectedLanguage(res)
            saveHistoryEntry("Live Q&A (" .. lang .. ")", question .. " → " .. res)
        else
            logError("Live Q&A error: " .. tostring(err))
            vibratePattern("error")
            notify("جواب نہیں مل سکا: " .. tostring(err))
        end
    end)
end

