-- ایک کوشش: فائل کو Groq Whisper پر بھیج کر متن لاتا ہے۔ (text, errorMessage, httpStatus)
local function groqTranscribeOnce(path, langCode)
    local apiKey = getAIApiKey()
    if not apiKey or apiKey == "" then
        return nil, "API Key missing! Set it in Settings.", 0
    end
    local file = File_CLASS(path)
    if not file.exists() or not file.canRead() then
        return nil, "The audio file cannot be read. It may have been moved or deleted, or the app may not have file access.", 0
    end
    local size = tonumber(file.length()) or 0
    if size <= 0 then return nil, "The audio file is empty.", 0 end
    if size > STT_MAX_BYTES then
        return nil, "This audio file is too large (" .. string.format("%.1f", size / 1048576) .. " MB). Groq's free limit is 25 MB.", 0
    end

    local name = tostring(file.getName())
    local ext = (name:match("%.([%w]+)$") or ""):lower()
    local sendExt = STT_UPLOAD_EXT[ext]
    if not sendExt then
        return nil, "The audio format \"." .. ext .. "\" is not supported by Groq. Supported: opus/ogg, mp3, m4a, wav, flac, webm, mp4.", 0
    end
    local uploadName = "voice." .. sendExt
    local mime = STT_MIME[sendExt] or "application/octet-stream"

    -- مین تھریڈ پر نیٹ ورک کی اجازت (ورنہ NetworkOnMainThreadException آتا ہے)
    pcall(function()
        local StrictMode = luajava.bindClass("android.os.StrictMode")
        StrictMode.setThreadPolicy(StrictMode.ThreadPolicy.Builder().permitAll().build())
    end)

    local boundary = "----CSRAudioBoundary" .. tostring(os.time()) .. tostring(math.random(100000, 999999))
    local CRLF = "\r\n"
    local function field(fname, value)
        return "--" .. boundary .. CRLF .. 'Content-Disposition: form-data; name="' .. fname .. '"' .. CRLF .. CRLF .. tostring(value) .. CRLF
    end
    local preamble = field("model", STT_MODEL) .. field("response_format", "json") .. field("temperature", "0")
    if langCode then preamble = preamble .. field("language", langCode) end
    preamble = preamble .. "--" .. boundary .. CRLF ..
        'Content-Disposition: form-data; name="file"; filename="' .. uploadName .. '"' .. CRLF ..
        "Content-Type: " .. mime .. CRLF .. CRLF
    local epilogue = CRLF .. "--" .. boundary .. "--" .. CRLF

    local statusCode = 0
    local body = ""
    local fis = nil
    local ok, err = pcall(function()
        local conn = URL(STT_URL).openConnection()
        conn.setRequestMethod("POST")
        conn.setDoOutput(true)
        conn.setConnectTimeout(15000)
        conn.setReadTimeout(120000)
        -- بڑی فائل کو پوری میموری میں جمع کیے بغیر ٹکڑوں میں بھیجیں
        if size > 4 * 1048576 then conn.setChunkedStreamingMode(0) end
        conn.setRequestProperty("Authorization", "Bearer " .. apiKey)
        conn.setRequestProperty("Content-Type", "multipart/form-data; boundary=" .. boundary)

        local out = conn.getOutputStream()
        local writer = OutputStreamWriter(out, "UTF-8")
        writer.write(preamble)
        writer.flush()

        fis = FileInputStream(file)
        local channel = fis.getChannel()
        local target = Channels.newChannel(out)
        local pos = 0
        while pos < size do
            local moved = tonumber(channel.transferTo(pos, size - pos, target)) or 0
            if moved <= 0 then break end
            pos = pos + moved
        end
        pcall(function() fis.close() end)
        fis = nil

        writer.write(epilogue)
        writer.flush()
        out.flush()
        out.close()

        statusCode = tonumber(conn.getResponseCode()) or 0
        local stream = nil
        if statusCode >= 200 and statusCode < 300 then
            stream = conn.getInputStream()
        else
            stream = conn.getErrorStream()
        end
        if stream then
            local reader = BufferedReader(InputStreamReader(stream, "UTF-8"))
            local parts = {}
            local line = reader.readLine()
            while line ~= nil do
                table.insert(parts, tostring(line))
                line = reader.readLine()
            end
            reader.close()
            body = table.concat(parts, "\n")
        end
    end)
    if fis then pcall(function() fis.close() end) end

    if not ok then
        logError("groqTranscribeOnce failed: " .. tostring(err))
        return nil, "Could not reach Groq (network problem): " .. tostring(err), 0
    end

    if statusCode == 200 then
        local decodeOk, decoded = pcall(cjson.decode, body)
        if decodeOk and type(decoded) == "table" and type(decoded.text) == "string" then
            return decoded.text, nil, 200
        end
        return nil, "Groq returned an unexpected answer.", 200
    end

    local msg = extractAIErrorMessage(body)
    if statusCode == 401 or statusCode == 403 then
        return nil, "Groq rejected the API key (" .. statusCode .. "). " .. tostring(msg or ""), statusCode
    elseif statusCode == 413 then
        return nil, "The audio file is too large for Groq.", statusCode
    elseif statusCode == 429 then
        local wait = parseRetryAfterSeconds(msg)
        return nil, "Groq's free limit for audio was reached" .. (wait and (". Try again in about " .. formatDuration(wait)) or "") .. ".", statusCode
    end
    return nil, "Error " .. tostring(statusCode) .. ": " .. tostring(msg or "no details"), statusCode
end

local function groqTranscribe(path, langCode)
    local text, err, status = groqTranscribeOnce(path, langCode)
    -- اگر Groq کو منتخب زبان کا کوڈ پسند نہ آئے (400) تو خودکار پہچان کے ساتھ ایک بار دوبارہ
    if not text and status == 400 and langCode and string.find(string.lower(tostring(err)), "language", 1, true) then
        text, err, status = groqTranscribeOnce(path, nil)
    end
    return text, err, status
end

