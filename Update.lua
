-- SHAKE-TO-ACTIVATE — فون کو ہلانے سے سیدھا Live Mode کھل جاتا ہے،
-- بغیر مینیو ڈھونڈے۔ ڈیفالٹ آف ہے (Settings سے آن کریں) تاکہ بلاوجہ
-- بیٹری استعمال یا غلطی سے ٹرگر نہ ہو۔
-- =====================================================================
local shakeState = {
    sensorManager = nil,
    listener = nil,
    accelSensor = nil,
    lastShakeTime = 0,
    registered = false
}

function isShakeEnabled() return aiPrefs.getBoolean("shake_enabled", false) end
function setShakeEnabled(v) aiEditor.putBoolean("shake_enabled", v); aiEditor.commit() end

-- Java float[] سے قدر نکالنے کے لیے محفوظ ہیلپر (چونکہ luajava میں
-- انڈیکسنگ 0-based یا 1-based ہونے کی یقین دہانی نہیں، دونوں آزماتے ہیں)
local function getArrVal(arr, javaIdx)
    local ok, v = pcall(function() return arr[javaIdx] end)
    if ok and v ~= nil then return v end
    local ok2, v2 = pcall(function() return arr[javaIdx + 1] end)
    if ok2 and v2 ~= nil then return v2 end
    return 0
end

function onShakeDetected()
    local now = os.time()
    if now - shakeState.lastShakeTime < 3 then return end  -- 3 سیکنڈ ڈی باؤنس
    shakeState.lastShakeTime = now
    logInfo("Shake detected — opening Live Mode.")
    vibratePattern("notify")
    local handler = Handler(Looper.getMainLooper())
    handler.post(Runnable({ run = function()
        pcall(function()
            if not liveModeState.active then
                startLiveMode()
            end
        end)
    end }))
end

function registerShakeListener()
    if shakeState.registered then return end
    local ok, err = pcall(function()
        shakeState.sensorManager = ctx.getSystemService(Context.SENSOR_SERVICE)
        shakeState.accelSensor = shakeState.sensorManager.getDefaultSensor(Sensor.TYPE_ACCELEROMETER)
        if not shakeState.accelSensor then
            logWarn("No accelerometer available — shake-to-activate not supported on this device.")
            return
        end
        shakeState.listener = SensorEventListener{
            onSensorChanged = function(event)
                local ok2, err2 = pcall(function()
                    local arr = event.values
                    local x = getArrVal(arr, 0)
                    local y = getArrVal(arr, 1)
                    local z = getArrVal(arr, 2)
                    local gX = x / SensorManager.GRAVITY_EARTH
                    local gY = y / SensorManager.GRAVITY_EARTH
                    local gZ = z / SensorManager.GRAVITY_EARTH
                    local gForce = math.sqrt(gX * gX + gY * gY + gZ * gZ)
                    if gForce > 2.2 then
                        onShakeDetected()
                    end
                end)
                if not ok2 then logError("Shake sensor processing error: " .. tostring(err2)) end
            end,
            onAccuracyChanged = function(sensor, accuracy) end
        }
        shakeState.sensorManager.registerListener(shakeState.listener, shakeState.accelSensor, SensorManager.SENSOR_DELAY_NORMAL)
        shakeState.registered = true
        logInfo("Shake-to-activate listener registered.")
    end)
    if not ok then
        logError("registerShakeListener failed: " .. tostring(err))
    end
end

function unregisterShakeListener()
    if not shakeState.registered then return end
    pcall(function()
        shakeState.sensorManager.unregisterListener(shakeState.listener)
    end)
    shakeState.registered = false
end

local liveModeState = {
