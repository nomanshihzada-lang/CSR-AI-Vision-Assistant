function processDocumentFrame(base64Data, statusTv, onFinished)
    local function finish()
        liveModeState.busy = false
        if onFinished then pcall(onFinished) end
    end
    local apiKey = getAIApiKey()
    if not apiKey or apiKey == "" then
        if statusTv then pcall(function() statusTv.setText("API Key missing — open Settings and add your key.") end) end
        finish()
        return
    end
    liveModeState.busy = true
    local lang = getSelectedLanguage()
    local prompt = "You are guiding a blind person who is holding a phone camera over a document, book page or paper. Look at the image. If one whole page or document is fully inside the frame and reasonably sharp and readable, reply with exactly the single word READY. Otherwise reply with exactly 'MOVE:' followed by one short instruction in " .. lang .. " telling the person how to move the phone (for example move a little to the left, move the phone further away, hold it steadier, or switch on more light). Write nothing else."
    callAIWithImage(apiKey, getAIModel(), base64Data, prompt, function(res, err, httpStatus, retryAfter)
        local paused = os.time() < liveModeState.pausedUntil
        if res then
            liveModeState.lastError = nil
            if not paused then
                local upper = string.upper(res)
                if string.find(upper, "READY", 1, true) and not string.find(upper, "MOVE", 1, true) then
                    finish()
                    vibratePattern("success")
                    documentReadNow(statusTv)
                    return
                end
                local hint = res:gsub("^%s*[Mm][Oo][Vv][Ee]%s*:%s*", "")
                if statusTv then pcall(function() statusTv.setText(hint) end) end
                local similar = liveModeState.lastSpokenText and (os.time() - (liveModeState.lastSpokeAt or 0)) < 20
                    and textSimilarity(hint, liveModeState.lastSpokenText) >= 0.7
                if not similar then
                    liveModeState.lastSpokenText = hint
                    liveModeState.lastSpokeAt = os.time()
                    speakInSelectedLanguage(hint, true)
                end
            end
        else
            logError("Document frame error: " .. tostring(err))
            if httpStatus == 429 then
                local pauseSec = math.min(tonumber(retryAfter) or 30, 300) + 1
                liveModeState.rateLimitedUntil = os.time() + pauseSec
            end
            if statusTv then pcall(function() statusTv.setText("⚠️ " .. tostring(err)) end) end
            local errKey = tostring(httpStatus or err)
            if errKey ~= liveModeState.lastError and not paused then
                liveModeState.lastError = errKey
                vibratePattern("error")
                speakInSelectedLanguage(tostring(err), true)
            end
        end
        finish()
    end, { maxTokens = 60, noCache = true, silentErrors = true, live = true })
end

-- profile.kind: "live" (ڈیفالٹ) | "camera" | "find" | "document"
function startLiveMode(profile)
    profile = profile or { kind = "live" }
    local kind = profile.kind or "live"
    if liveModeState.active then
        notify("A camera screen is already running.")
        return
    end
    if mainDlg then pcall(function() mainDlg.dismiss() end) mainDlg = nil end
