        addButton(liveLayout, "🎯 Change What I Am Looking For", "Change the object you are looking for", function()
            stopLiveMode()
            pcall(function() liveDlg.dismiss() end)
            showFindObjectDialog()
        end)
    elseif kind == "document" then
        title = "Document Reader"
        addButton(liveLayout, "📸 SCAN NOW", "Read the page in front of the camera now", function() documentReadNow(statusTv) end, 0xFF4CAF50)
