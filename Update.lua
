local function collectAudioFiles(dirPath, depth, out)
    local readable = false
    pcall(function()
        local dir = File_CLASS(dirPath)
        if dir.exists() and dir.isDirectory() then
            local arr = dir.listFiles()
            if arr then
                readable = true
                local lst = Arrays.asList(arr)
                for i = 0, lst.size() - 1 do
                    local f = lst.get(i)
                    local name = tostring(f.getName())
                    if f.isDirectory() then
                        if depth < 2 then
                            collectAudioFiles(tostring(f.getAbsolutePath()), depth + 1, out)
                        end
                    else
                        local ext = (name:match("%.([%w]+)$") or ""):lower()
                        if AUDIO_EXTENSIONS[ext] then
                            table.insert(out, {
                                path = tostring(f.getAbsolutePath()),
                                name = name,
                                time = tonumber(f.lastModified()) or 0,
                                size = tonumber(f.length()) or 0
                            })
                        end
                    end
                end
            end
        end
    end)
    return readable
end

