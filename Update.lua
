-- موجودہ اسکرین کے نظر آنے والے متن جمع کرتا ہے (Screen Translator / Describe Current Screen)
local function collectScreenTexts(limitChars)
    local root = nil
    pcall(function() root = service.getRootInActiveWindow() end)
    if not root then return nil end
    local items = {}
    local total = 0
    local function walk(node, depth)
        if depth > 14 or total > limitChars then return end
        local visible = false
        pcall(function() visible = node.isVisibleToUser() end)
        if not visible then return end
        local text, desc = "", ""
        pcall(function()
            local t = node.getText()
            if t then text = tostring(t) end
        end)
        pcall(function()
            local d = node.getContentDescription()
            if d then desc = tostring(d) end
        end)
        local label = text
        if label == "" then label = desc end
        if label ~= "" and items[#items] ~= label then
            table.insert(items, label)
            total = total + #label
        end
        local count = 0
        pcall(function() count = node.getChildCount() end)
        for i = 0, count - 1 do
            local child = nil
            pcall(function() child = node.getChild(i) end)
            if child then walk(child, depth + 1) end
        end
    end
    walk(root, 0)
    return items
end

