-- =====================================================================
-- PERMISSIONS CHECK SCREEN — ایپ کے اہم فیچرز کے لیے درکار پرمیشنز کی
-- حالت ایک ہی جگہ دکھاتا ہے، اور ٹھیک کرنے کے لیے سیدھا App Settings
-- کھولتا ہے (Service context سے براہ راست پرمیشن مانگنا ممکن نہیں،
-- اس لیے یہی سب سے قابلِ اعتماد طریقہ ہے)۔
-- =====================================================================
function hasPermission(permString)
    local ok, result = pcall(function()
        return ctx.checkSelfPermission(permString) == PackageManager.PERMISSION_GRANTED
    end)
    if ok then return result end
    return true -- چیک ناکام ہونے کی صورت میں کوشش کرنے دیں
end

function openAppSettingsScreen()
    local ok, err = pcall(function()
        local intent = Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS)
        local uri = Uri.fromParts("package", ctx.getPackageName(), nil)
        intent.setData(uri)
        intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        ctx.startActivity(intent)
    end)
    if not ok then
        logError("openAppSettingsScreen failed: " .. tostring(err))
        notify("App Settings نہیں کھل سکیں")
    end
end

function showPermissionsDialog()
    local hasCamera = hasPermission(Manifest.permission.CAMERA)
    local hasMic = hasPermission(Manifest.permission.RECORD_AUDIO)
    local hasStorage = hasPermission(Manifest.permission.READ_MEDIA_IMAGES) or hasPermission("android.permission.READ_EXTERNAL_STORAGE")

    local layout = LinearLayout(ctx)
    layout.setOrientation(1)
    layout.setPadding(30, 20, 30, 20)

    local function addRow(label, granted, usedFor)
        local tv = TextView(ctx)
        local mark = granted and "✅" or "❌"
        tv.setText(mark .. "  " .. label .. "\n     (" .. usedFor .. ")")
        tv.setTextSize(14)
        tv.setPadding(0, 10, 0, 10)
        layout.addView(tv)
    end

    addRow("Camera", hasCamera, "Live Navigation Mode کے لیے")
    addRow("Microphone", hasMic, "Voice Q&A سوال پوچھنے کے لیے")
    addRow("Photos/Storage", hasStorage, "Gallery سے تصویر منتخب کرنے کے لیے")

    if hasCamera and hasMic and hasStorage then
        local okTv = TextView(ctx)
        okTv.setText("\nسب پرمیشنز موجود ہیں۔ آپ ایپ کے تمام فیچرز استعمال کر سکتے ہیں۔")
        okTv.setTextSize(13)
        okTv.setTextColor(0xFF4CAF50)
        layout.addView(okTv)
    else
        local hintTv = TextView(ctx)
        hintTv.setText("\nجو پرمیشن ❌ ہے، اسے 'Open App Settings' سے جا کر آن کریں۔")
        hintTv.setTextSize(12)
        hintTv.setTextColor(0xFF888888)
        layout.addView(hintTv)
    end

    local dlg = LuaDialog(ctx)
    dlg.setTitle("Permissions Status")
    dlg.setView(layout)
    dlg.setPositiveButton("Open App Settings", function()
        openAppSettingsScreen()
    end)
