function buildPromptForMode(selectedOption, lang)
    if selectedOption == "Extract Text Only" then
        local custom = getCustomPrompt("extract")
        return (custom ~= "" and custom) or "Extract only the text from this image. Output the text exactly as seen."
    elseif selectedOption == "Translate Image Text" then
        local custom = getCustomPrompt("translate")
        return (custom ~= "" and custom .. " Target language: " .. lang .. ".") or ("Extract all text from this image and accurately translate it into " .. lang .. ". Provide only the translated text.")
    elseif selectedOption == "Summarize Document" then
        local custom = getCustomPrompt("summarize")
        return (custom ~= "" and custom .. " Provide the final output in " .. lang .. ".") or ("Perform an advanced document analysis on this image. Please structure the output beautifully with clear headings. 1. 'Executive Summary': Provide a concise summary of the document's main purpose. 2. 'Key Information': Extract critical entities like Important Dates, Total Amounts, Names, and Reference Numbers. 3. 'Actionable Insights': Suggest what needs to be done next based on this document. Provide the final output in " .. lang)
    elseif selectedOption == "Label & Medicine Reader" then
        local custom = getCustomPrompt("label")
        return (custom ~= "" and custom .. " Reply in " .. lang .. ".") or ("Read the product or medicine package/label shown in this image and report it clearly, in this order: 1) the product or medicine name; 2) what it is (only if printed on the pack); 3) strength, dosage and usage directions exactly as printed; 4) expiry date, manufacture date and batch number if visible; 5) ingredients and warnings if visible. Read ONLY what is actually printed — never guess or invent anything. If a part is unreadable or cut off, say so and suggest holding the camera closer or improving the light. For medicines, end with a one-line reminder to confirm the dosage with a doctor or pharmacist. Keep brand names as printed. Reply in " .. lang .. ".")
    else
        local custom = getCustomPrompt("analyze")
        return (custom ~= "" and custom .. " Provide the response in " .. lang .. ".") or ("Analyze this image in detail. Describe what you see, including objects, people, text, colors, and context. Provide the response in " .. lang)
    end
end

function scanAllImages()
    notify("Scanning images...")
    local foundFiles = {}
    local contentResolver = ctx.getContentResolver()
    local uri = MediaStore.Images.Media.EXTERNAL_CONTENT_URI
    local projection = { MediaStore.Images.Media.DATA, MediaStore.Images.Media.DISPLAY_NAME }
    local cursor = contentResolver.query(uri, projection, nil, nil, MediaStore.Images.Media.DATE_ADDED .. " DESC")
    
    if cursor ~= nil then
        local dataCol = cursor.getColumnIndexOrThrow(MediaStore.Images.Media.DATA)
        local nameCol = cursor.getColumnIndexOrThrow(MediaStore.Images.Media.DISPLAY_NAME)
        local count = 0
        while cursor.moveToNext() and count < 100 do
            local path = cursor.getString(dataCol)
            local name = cursor.getString(nameCol)
            if path and name then
                table.insert(foundFiles, {path = path, name = name})
                count = count + 1
            end
        end
        cursor.close()
    else
        notify("Unable to access images. Storage permission may be missing.")
        return
    end
    
    if #foundFiles > 0 then
        local adapterData = {}
        photoFilePaths = {}
        for _, file in ipairs(foundFiles) do
            table.insert(adapterData, file.name)
            table.insert(photoFilePaths, file.path)
        end
        
        local listLayout = LinearLayout(ctx)
        listLayout.setOrientation(1)
        local listView = ListView(ctx)
        listView.setAdapter(ArrayAdapter(ctx, android.R.layout.simple_list_item_1, adapterData))
        listLayout.addView(listView)
        
        local listDlg = LuaDialog(ctx)
        listDlg.setTitle("Select Image (Last 100)")
        listDlg.setView(listLayout)
        listDlg.show()
        
        listView.setOnItemClickListener(AdapterView.OnItemClickListener{
            onItemClick = function(p, v, pos, id)
                selectedPhotoPath = photoFilePaths[pos + 1]
                selectedPhotoUri = nil
                if _G.statusLabel then
                    _G.statusLabel.setText("Selected: " .. File_CLASS(selectedPhotoPath).getName())
                end
                notify("Selected: " .. File_CLASS(selectedPhotoPath).getName())
                listDlg.dismiss()
            end
        })
    else
        notify("No images found.")
    end
end

