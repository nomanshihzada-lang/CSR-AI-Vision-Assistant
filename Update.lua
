    local startTexts = {
        live = "Live Mode active — the first description is coming...",
        camera = "Point the camera at what you want to know about, then tap Capture.",
        find = "Looking for: " .. tostring(profile.target or "") .. ". Turn slowly.",
        document = "Hold the phone above the page. I will guide you and read it when the whole page is in view."
    }

    local holder = surfaceView.getHolder()
    holder.addCallback(SurfaceHolder.Callback{
        surfaceCreated = guard("surfaceCreated (camera)", function(h)
            local ok, err = pcall(function()
                liveModeState.holder = h
                openLiveCamera(h)
                liveModeState.active = true
                liveModeState.busy = false
                liveModeState.pausedUntil = 0
                liveModeState.rateLimitedUntil = 0
                statusTv.setText(startTexts[kind] or startTexts.live)
