            summarize = getCustomPrompt("summarize"),
            live = getCustomPrompt("live"),
            qa = getCustomPrompt("qa")
        }
    }
    local ok, json = pcall(cjson.encode, data)
    if ok then return json end
    logError("exportSettingsAsJSON failed: " .. tostring(json))
