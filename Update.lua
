function writeLog(level, message)
    if not CONFIG.LOG_ENABLED or not logFilePath then return end
    pcall(function()
        local timeStr = os.date("%Y-%m-%d %H:%M:%S")
        local line = string.format("[%s] [%s] %s\n", timeStr, level, tostring(message))

        -- لائن کاؤنٹ کی حد کو برقرار رکھنے کے لیے، فائل بہت بڑی ہو جانے پر پرانی لائنیں ہٹا دیں
        local f = io.open(logFilePath, "r")
        if f then
            local lines = {}
            for l in f:lines() do table.insert(lines, l) end
            f:close()
            if #lines >= CONFIG.LOG_MAX_LINES then
                local trimmed = {}
                local startIdx = #lines - CONFIG.LOG_MAX_LINES + 1
                for i = startIdx, #lines do table.insert(trimmed, lines[i]) end
                local wf = io.open(logFilePath, "w")
                if wf then
                    for _, l in ipairs(trimmed) do wf:write(l .. "\n") end
                    wf:close()
                end
            end
        end

        local af = io.open(logFilePath, "a")
        if af then
            af:write(line)
            af:close()
        end
    end)
end

function logInfo(msg) writeLog("INFO", msg) end
function logWarn(msg) writeLog("WARN", msg) end
function logError(msg) writeLog("ERROR", msg) end

function shareLogFile()
    if not logFilePath then
        notify("Log file not available")
        return
    end
    local f = File_CLASS(logFilePath)
    if not f.exists() then
        notify("No log file found yet")
        return
    end

    -- نوٹ: پہلے یہاں Uri.fromFile() استعمال ہو رہا تھا جو Android 7+ پر
    -- FileUriExposedException دیتا ہے (چاہے پکال میں ہو، شیئر خاموشی سے
    -- ناکام ہو جاتا ہے)۔ اب لاگ کا متن براہِ راست ٹیکسٹ کے طور پر شیئر
    -- کیا جاتا ہے — کسی فائل یوآرآئی کی ضرورت نہیں۔
    local readOk, content = pcall(function()
        local rf = io.open(logFilePath, "r")
        if not rf then return nil end
        local data = rf:read("*a")
        rf:close()
        return data
    end)
    if not readOk or not content or content == "" then
        vibratePattern("error")
        notify("Log file پڑھنے میں مسئلہ ہوا")
        logError("shareLogFile: could not read log content")
        return
    end
    if #content > 30000 then
        content = "...(truncated)...\n" .. content:sub(-30000)
    end

    local shareOk, shareErr = pcall(function()
        local shareIntent = Intent(Intent.ACTION_SEND)
        shareIntent.setType("text/plain")
        shareIntent.putExtra(Intent.EXTRA_SUBJECT, "CSR AI Assistant Log")
        shareIntent.putExtra(Intent.EXTRA_TEXT, content)
        local chooser = Intent.createChooser(shareIntent, "Share Log")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        ctx.startActivity(chooser)
    end)
    if not shareOk then
        logError("shareLogFile: share failed: " .. tostring(shareErr))
        vibratePattern("error")
        notify("Share نہیں ہو سکا: " .. tostring(shareErr))
    end
end

