-- NETWORK CHECK + OFFLINE OCR FALLBACK
-- انٹرنیٹ نہ ہونے کی صورت میں "Extract Text Only" موڈ کے لیے مقامی
-- (آن-ڈیوائس) OCR آزمائی جاتی ہے۔ باقی موڈز (Analyze/Translate/Summarize)
-- کو AI reasoning چاہیے، اس لیے وہ صرف انٹرنیٹ کے ساتھ ہی کام کریں گے۔
--
-- نوٹ: یہ Tesseract OCR کلاس (com.googlecode.tesseract.android.TessBaseAPI)
-- استعمال کرتی ہے، جو صرف اسی صورت دستیاب ہوگی جب آپ کے AndroLua ایڈیشن
-- میں یہ پلگ ان پہلے سے شامل ہو اور CONFIG.OCR_TESSDATA_DIR کے اندر
-- "tessdata/eng.traineddata" فائل موجود ہو۔ اگر یہ کلاس یا فائل موجود نہ
-- ہو تو ایپ کریش نہیں ہوگی — صرف واضح پیغام دے گی۔
-- =====================================================================
function isNetworkAvailable()
    local ok, result = pcall(function()
        local cm = ctx.getSystemService(Context.CONNECTIVITY_SERVICE)
        if not cm then return true end
        local network = cm.getActiveNetwork()
        if not network then return false end
        local capabilities = cm.getNetworkCapabilities(network)
        if not capabilities then return false end
        return capabilities.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)
    end)
    if ok then return result end
    -- چیک ناکام ہونے کی صورت میں پرامی ٹیکل طور پر آن لائن فرض کریں
    -- (تاکہ ایک غلط نیٹ ورک چیک کی وجہ سے فیچر مکمل بند نہ ہو جائے)
    logWarn("isNetworkAvailable check failed, assuming online: " .. tostring(result))
    return true
end

function tryOfflineOCR(callback)
    logInfo("Attempting offline OCR fallback for current selection")
    local ok, resultOrErr = pcall(function()
        local TessBaseAPI_CLASS = luajava.bindClass("com.googlecode.tesseract.android.TessBaseAPI")
        local tess = TessBaseAPI_CLASS()
        local dataPath = (os.getenv("EXTERNAL_STORAGE") or "/sdcard") .. "/" .. CONFIG.OCR_TESSDATA_DIR
        local initOk = tess.init(dataPath, CONFIG.OCR_LANGUAGE)
        if not initOk then
            pcall(function() tess.recycle() end)
            error("Tesseract init failed — tessdata/" .. CONFIG.OCR_LANGUAGE .. ".traineddata missing?")
        end
        local bitmap = decodeSelectedBitmap()
        if not bitmap then
            pcall(function() tess.recycle() end)
            error("Could not decode image for OCR")
        end
        tess.setImage(bitmap)
        local text = tess.getUTF8Text()
        tess.recycle()
        bitmap.recycle()
        return text
    end)

    if ok and resultOrErr and resultOrErr ~= "" then
        logInfo("Offline OCR succeeded.")
        callback(resultOrErr, nil)
    else
        logWarn("Offline OCR unavailable/failed: " .. tostring(resultOrErr))
        callback(nil, "انٹرنیٹ دستیاب نہیں اور آفلائن OCR بھی اس ڈیوائس پر دستیاب/فعال نہیں ہے۔\n\nمشورہ: انٹرنیٹ کنکشن آن کر کے دوبارہ کوشش کریں، یا Tesseract OCR پلگ ان اور tessdata فائل انسٹال کریں۔")
    end
end

