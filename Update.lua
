function createCameraOutputUri()
    local ok, result = pcall(function()
        local values = ContentValues()
        values.put(MediaStore.Images.Media.DISPLAY_NAME, "CSR_AI_" .. os.time() .. ".jpg")
        values.put(MediaStore.Images.Media.MIME_TYPE, "image/jpeg")
        local resolver = ctx.getContentResolver()
        return resolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, values)
    end)
    if ok and result then
        logInfo("createCameraOutputUri: created new MediaStore entry")
        return result
    end
    logError("createCameraOutputUri failed: " .. tostring(result))
    return nil
end

-- content:// URI سے براہِ راست بیس 64 حاصل کریں (کیمرے سے آنے والی تصویر کے لیے)
function uriToBase64(uri)
    local ok, result = pcall(function()
        local resolver = ctx.getContentResolver()
        local inputStream = resolver.openInputStream(uri)
        if not inputStream then return nil end

        local options = BitmapFactory.Options()
        options.inPreferredConfig = Bitmap.Config.RGB_565
        local bitmap = BitmapFactory.decodeStream(inputStream, nil, options)
        pcall(function() inputStream.close() end)
        if not bitmap then return nil end

        local maxDimension = CONFIG.MAX_IMAGE_DIMENSION
        local width = bitmap.getWidth()
        local height = bitmap.getHeight()
        if width > maxDimension or height > maxDimension then
            local newWidth, newHeight = width, height
            if width > height then
                newWidth = maxDimension
                newHeight = (height * maxDimension / width)
            else
                newHeight = maxDimension
                newWidth = (width * maxDimension / height)
            end
            local scaled = Bitmap.createScaledBitmap(bitmap, newWidth, newHeight, true)
            bitmap.recycle()
            bitmap = scaled
        end

        local outputStream = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.JPEG, CONFIG.JPEG_QUALITY, outputStream)
        local imageBytes = outputStream.toByteArray()
        outputStream.close()
        bitmap.recycle()
        collectgarbage("collect")
        return Base64.encodeToString(imageBytes, Base64.NO_WRAP)
    end)
    if ok and result then
        logInfo("uriToBase64: image encoded from content URI")
        return result
    end
    logError("uriToBase64 failed: " .. tostring(result))
    return nil
end

