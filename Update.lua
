-- بولنے/ٹاک بیک کے لیے متن صاف کرتا ہے: مارک ڈاؤن علامات (* # `) اور بلٹ ہٹاتا ہے
function cleanForSpeech(text)
    if not text then return "" end
    local s = tostring(text)
    s = s:gsub("[%*#`]", "")
    s = s:gsub("\226\128\162", "")
    s = s:gsub("\n%s*%-%s+", "\n")
    return s
end

-- بٹن کے متن سے ایموجی/علامات ہٹا کر ٹاک بیک کے لیے صاف نام بناتا ہے
function cleanLabel(text)
    local s = tostring(text or "")
    s = s:gsub("[\240-\244][\128-\191]*", "")
    s = s:gsub("\226[\154-\157][\128-\191]", "")
    s = s:gsub("\226\150[\182\183]", "")
    s = s:gsub("\226\143[\128-\191]", "")
    s = s:gsub("\239\184[\128-\143]", "")
    s = s:gsub("\226\128\162", "")
    s = s:gsub("%s+", " ")
    s = s:gsub("^%s+", ""):gsub("%s+$", "")
    return s
end

-- ویو کے درخت میں ہر بٹن/ٹیکسٹ کو ٹاک بیک کے لیے صاف contentDescription دیتا ہے
-- (صرف تب جب ایموجی ہٹانے سے متن بدلتا ہو؛ EditText کو کبھی نہیں چھیڑتا تاکہ
-- API key جیسا لکھا ہوا متن ٹاک بیک پر نہ بولا جائے)
function applyAccessibilityLabels(view, depth)
    depth = depth or 0
    if not view or depth > 14 then return end
    pcall(function()
        local simpleName = ""
        pcall(function() simpleName = tostring(view.getClass().getSimpleName()) end)
        if simpleName ~= "EditText" then
            local existing = nil
            pcall(function() existing = view.getContentDescription() end)
            if existing == nil or tostring(existing) == "" then
                local text = nil
                pcall(function() text = view.getText() end)
                if text ~= nil and tostring(text) ~= "" then
                    local original = tostring(text)
                    local label = cleanLabel(original)
                    if label ~= "" and label ~= original then
                        view.setContentDescription(label)
                    end
                end
            end
        end
    end)
    local count = 0
    pcall(function() count = view.getChildCount() end)
    for i = 0, count - 1 do
        local child = nil
        pcall(function() child = view.getChildAt(i) end)
        if child then applyAccessibilityLabels(child, depth + 1) end
    end
end

-- کسی بھی ہینڈلر (بٹن، ڈائیلاگ بٹن، کال بیک) کو لپیٹتا ہے: اگر اس کے اندر Lua
-- ایرر آئے تو خاموشی سے ضائع ہونے کے بجائے ایرر ڈائیلاگ میں پوری تفصیل دکھاتا ہے
function guard(name, fn)
    return function(...)
        local ok, result = pcall(fn, ...)
        if not ok then
            pcall(reportError, name, tostring(result))
            return nil
        end
        return result
    end
end

-- UTF-8 متن کو بائٹس کی حد پر کاٹتا ہے، لیکن کسی حرف کے بیچ میں نہیں
-- (ورنہ ٹوٹا ہوا UTF-8 JSON/API میں ایرر دیتا ہے — اردو میں ہر حرف 2 بائٹ کا ہوتا ہے)
function safeUtf8Cut(s, maxBytes)
    s = tostring(s or "")
    if #s <= maxBytes then return s end
    local cut = maxBytes
    while cut > 0 do
        local b = string.byte(s, cut + 1)
        if b and b >= 128 and b < 192 then
            cut = cut - 1
        else
            break
        end
    end
    return s:sub(1, cut)
end

