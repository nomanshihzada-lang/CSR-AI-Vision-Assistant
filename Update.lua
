-- دو جملوں کی مشابہت (0 سے 1): مشترک الفاظ / کل الگ الفاظ
local function wordSetOf(s)
    local set, n = {}, 0
    for w in tostring(s):lower():gmatch("%S+") do
        w = w:gsub("%p", "")
        if w ~= "" and not set[w] then
            set[w] = true
            n = n + 1
        end
    end
    return set, n
end

local function textSimilarity(a, b)
    local sa, na = wordSetOf(a)
    local sb, nb = wordSetOf(b)
    if na == 0 or nb == 0 then return 0 end
    local common = 0
    for w in pairs(sa) do
        if sb[w] then common = common + 1 end
    end
    return common / (na + nb - common)
end

-- ایک فریم کی تفصیل بولتا ہے۔ onFinished: کام ختم ہونے پر (تاکہ اگلا کیپچر شیڈول ہو)
function processLiveFrame(base64Data, statusTv, onFinished)
    local function finish()
        liveModeState.busy = false
        if onFinished then pcall(onFinished) end
    end

    local apiKey = getAIApiKey()
    if not apiKey or apiKey == "" then
        if statusTv then pcall(function() statusTv.setText("API Key missing — Settings کھول کر key ڈالیں۔") end) end
        finish()
        return
    end
    liveModeState.busy = true
    local lang = getSelectedLanguage()
    local custom = getCustomPrompt("live")
    local basePrompt
    local profile = liveModeState.profile or {}
    if profile.kind == "find" and profile.target and profile.target ~= "" then
        basePrompt = "The user is blind and is looking for: \"" .. profile.target .. "\". Look at the image and reply in exactly ONE short sentence (max 15 words). If you can see it, say where it is (left, right, centre, above or below), roughly how far away in steps, and what the user should do (for example turn slightly left, or walk forward). If you cannot see it, say briefly that it is not visible and suggest turning slowly."
    elseif custom ~= "" then
        basePrompt = custom
    else
        basePrompt = "Reply in exactly ONE short, natural, spoken-style sentence (max 12 words). Describe anything important directly ahead for a visually impaired person walking: people, obstacles, stairs, vehicles, doors, or hazards. If something notable is present, include a rough approximate distance (e.g. 'a few steps ahead', 'right in front of you', 'about 2 meters away') based on visual perspective — this is only an estimate, not exact. If the path is clear, say so."
    end
    local prompt = basePrompt .. " IMPORTANT: your entire reply must be written ONLY in " .. lang .. ". Do not use English or any other language, not even a single word (unless " .. lang .. " itself is English). Do not add labels, quotes, or any extra text — output only the spoken sentence."
    callAIWithImage(apiKey, getAIModel(), base64Data, prompt, function(res, err, httpStatus, retryAfter)
        -- اگر اسی دوران صارف نے سوال پوچھنا شروع کر دیا ہو تو یہ خودکار جواب بولیں نہیں
        local paused = os.time() < liveModeState.pausedUntil
        if res then
            liveModeState.lastError = nil
            if not paused then
                -- اگر منظر پچھلی تفصیل جیسا ہی ہے تو دوبارہ نہ بولیں (40 سیکنڈ بعد تسلی کے لیے پھر بولتا ہے)
                local similar = false
                if isSpeakOnlyOnChange() and liveModeState.lastSpokenText
                        and (os.time() - (liveModeState.lastSpokeAt or 0)) < 40 then
                    similar = textSimilarity(res, liveModeState.lastSpokenText) >= 0.7
                end
                if similar then
                    liveModeState.unchangedStreak = (liveModeState.unchangedStreak or 0) + 1
                    if statusTv then pcall(function() statusTv.setText(res .. "\n\n(no change)") end) end
                else
                    liveModeState.unchangedStreak = 0
                    liveModeState.lastSpokenText = res
                    if statusTv then pcall(function() statusTv.setText(res) end) end
                    liveModeState.lastSpokeAt = os.time()
                    speakInSelectedLanguage(res)
                    saveHistoryEntry("Live Mode (" .. lang .. ")", res)
                end
            end
        else
            logError("Live frame error: " .. tostring(err))
            -- Rate limit لگنے پر لائیو لوپ Groq کے بتائے وقت (زیادہ سے زیادہ 5 منٹ) تک رک جاتا ہے،
            -- بار بار درخواستیں بھیج کر حد کو اور خراب نہیں کرتا
            if httpStatus == 429 then
                local pauseSec = math.min(tonumber(retryAfter) or 30, 300) + 1
                liveModeState.rateLimitedUntil = os.time() + pauseSec
            end
            if statusTv then pcall(function() statusTv.setText("⚠️ " .. tostring(err)) end) end
            -- ہر مختلف قسم کا ایرر صرف ایک بار بولیں (وقت بدلنے سے پیغام مختلف نہ سمجھا جائے)
            local errKey = tostring(httpStatus or err)
            if errKey ~= liveModeState.lastError and not paused then
                liveModeState.lastError = errKey
                vibratePattern("error")
                speakInSelectedLanguage(tostring(err))
            end
        end
        finish()
    end, { maxTokens = 120, noCache = true, silentErrors = true, live = true })
end

