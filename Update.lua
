-- بھیجا جاتا تھا۔ Android 7 (API 24) سے، ایسا کوئی بھی URI جو آپ کی ایپ
-- سے باہر (دوسری ایپ کو) بھیجا جائے، FileUriExposedException دیتا ہے —
-- یہ ایک fatal/uncaught exception ہے جو پورے پراسیس کو کریش کر سکتا ہے،
-- اور چونکہ یہ ایک Accessibility Service کے اندر ہو رہا تھا، بار بار
-- کریش ہونے سے سسٹم اَنسٹیبل ہو کر ڈیوائس ری اسٹارٹ جیسا برتاؤ دکھا سکتا
-- ہے۔ اوپر موجود StrictMode کوڈ اسے حل نہیں کرتا کیونکہ یہ چیک
-- StrictMode کی پالیسی سے آزاد، فریم ورک میں خود بخود لاگو ہوتا ہے۔
--
-- نیا/محفوظ طریقہ: ContentResolver.insert() کے ذریعے براہِ راست
-- MediaStore میں ایک نئی خالی entry بنائی جاتی ہے، جو ایک اصلی
-- "content://" URI دیتی ہے — یہ کبھی FileUriExposedException نہیں دیتا
-- اور کسی FileProvider/Manifest تبدیلی کی ضرورت نہیں پڑتی۔
