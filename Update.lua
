function stopLiveMode()
    liveModeState.active = false
    if liveModeState.camera then
        pcall(function()
            liveModeState.camera.setPreviewCallback(nil)
            liveModeState.camera.stopPreview()
            liveModeState.camera.release()
        end)
        liveModeState.camera = nil
    end
    stopTTS()
    liveModeState.busy = false
    liveModeState.pausedUntil = 0
    liveModeState.lastError = nil
    logInfo("Live Mode stopped.")
end

-- کیمرے کا سینسر گھماؤ (عموماً 90°)۔ کیمرہ فریم اسی زاویے پر "لیٹے ہوئے" آتے
-- ہیں، اس لیے AI کو بھیجنے سے پہلے سیدھا کیا جاتا ہے — اس سے جواب کی درستگی بہتر ہوتی ہے
local function getCameraRotation()
    if liveModeState.cameraRotation then return liveModeState.cameraRotation end
    local rot = 90
    pcall(function()
        local info = Camera.CameraInfo()
        Camera.getCameraInfo(0, info)
        rot = tonumber(info.orientation) or 90
    end)
    liveModeState.cameraRotation = rot
    return rot
end

function nv21ToJpegBase64(data, camera)
    local ok, result = pcall(function()
        local params = camera.getParameters()
        local size = params.getPreviewSize()
        local yuvImage = YuvImage(data, ImageFormat.NV21, size.width, size.height, nil)
        local out = ByteArrayOutputStream()
        local rect = Rect(0, 0, size.width, size.height)
        yuvImage.compressToJpeg(rect, 65, out)
        local bytes = out.toByteArray()
        out.close()

        -- فریم کو سیدھا کریں (ناکام ہو تو بغیر گھمائے ہی بھیج دیں)
        local rot = getCameraRotation()
        if rot ~= 0 then
            pcall(function()
                local bmp = BitmapFactory.decodeByteArray(bytes, 0, #bytes)
                if bmp then
                    local m = Matrix()
                    m.postRotate(rot)
                    local rotated = Bitmap.createBitmap(bmp, 0, 0, bmp.getWidth(), bmp.getHeight(), m, true)
                    bmp.recycle()
                    local out2 = ByteArrayOutputStream()
                    rotated.compress(Bitmap.CompressFormat.JPEG, 70, out2)
                    bytes = out2.toByteArray()
                    out2.close()
                    rotated.recycle()
                end
            end)
        end
        return Base64.encodeToString(bytes, Base64.NO_WRAP)
    end)
    if ok then return result end
    logError("nv21ToJpegBase64 failed: " .. tostring(result))
    return nil
end

-- کیمرے سے ایک تازہ فریم لیتا ہے (کال بیک میں base64 یا nil)۔ 2.5 سیکنڈ میں
-- نہ ملے تو nil کے ساتھ واپس آ جاتا ہے تاکہ کچھ اٹکے نہیں۔
function captureFreshFrame(callback)
    if not (liveModeState.active and liveModeState.camera) then
        callback(nil)
        return
    end
    local done = false
    local ok = pcall(function()
        liveModeState.camera.setOneShotPreviewCallback(Camera.PreviewCallback{
            onPreviewFrame = function(data, cam)
                if done then return end
                done = true
                local b64 = nv21ToJpegBase64(data, cam)
                if b64 then liveModeState.lastFrameBase64 = b64 end
                callback(b64)
            end
        })
    end)
    if not ok then
        callback(nil)
        return
    end
    local handler = Handler(Looper.getMainLooper())
    handler.postDelayed(Runnable({ run = function()
        if not done then
            done = true
            callback(nil)
        end
    end }), 2500)
end

-- ایک فریم کی تفصیل بولتا ہے۔ onFinished: کام ختم ہونے پر (تاکہ اگلا کیپچر شیڈول ہو)
function processLiveFrame(base64Data, statusTv, onFinished)
    local function finish()
        liveModeState.busy = false
        if onFinished then pcall(onFinished) end
    end

    local apiKey = getAIApiKey()
    if not apiKey or apiKey == "" then
        if statusTv then pcall(function() statusTv.setText("API Key missing — Settings کھول کر key ڈالیں۔") end) end
        finish()
        return
    end
    liveModeState.busy = true
    local lang = getSelectedLanguage()
    local custom = getCustomPrompt("live")
    local basePrompt
    if custom ~= "" then
        basePrompt = custom
    else
        basePrompt = "Reply in exactly ONE short, natural, spoken-style sentence (max 12 words). Describe anything important directly ahead for a visually impaired person walking: people, obstacles, stairs, vehicles, doors, or hazards. If something notable is present, include a rough approximate distance (e.g. 'a few steps ahead', 'right in front of you', 'about 2 meters away') based on visual perspective — this is only an estimate, not exact. If the path is clear, say so."
    end
    local prompt = basePrompt .. " IMPORTANT: your entire reply must be written ONLY in " .. lang .. ". Do not use English or any other language, not even a single word (unless " .. lang .. " itself is English). Do not add labels, quotes, or any extra text — output only the spoken sentence."
    callAIWithImage(apiKey, getAIModel(), base64Data, prompt, function(res, err)
        -- اگر اسی دوران صارف نے سوال پوچھنا شروع کر دیا ہو تو یہ خودکار جواب بولیں نہیں
        local paused = os.time() < liveModeState.pausedUntil
        if res then
            liveModeState.lastError = nil
            if not paused then
                if statusTv then pcall(function() statusTv.setText(res) end) end
                liveModeState.lastSpokeAt = os.time()
                speakInSelectedLanguage(res)
                saveHistoryEntry("Live Mode (" .. lang .. ")", res)
            end
        else
            logError("Live frame error: " .. tostring(err))
            if statusTv then pcall(function() statusTv.setText("⚠️ " .. tostring(err)) end) end
            -- ہر مختلف ایرر صرف ایک بار بولیں (بار بار بولنے سے تنگ نہ ہو)
            if err ~= liveModeState.lastError and not paused then
                liveModeState.lastError = err
                vibratePattern("error")
                speakInSelectedLanguage(tostring(err))
            end
        end
        finish()
    end, { maxTokens = 150, noCache = true })
end

