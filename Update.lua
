function recordTokenUsage(usage)
    if not usage or type(usage) ~= "table" then return end
    -- Groq (OpenAI-سٹائل): prompt_tokens/completion_tokens/total_tokens
    -- (input_tokens/output_tokens بھی قبول کیے جاتے ہیں)
    local promptTokens = tonumber(usage.input_tokens) or tonumber(usage.prompt_tokens) or 0
    local responseTokens = tonumber(usage.output_tokens) or tonumber(usage.completion_tokens) or 0
    local totalTokens = tonumber(usage.total_tokens) or (promptTokens + responseTokens)

    pcall(function()
        local today = getTodayDateString()
        local month = getCurrentMonthString()

