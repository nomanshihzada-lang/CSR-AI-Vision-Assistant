        elseif selectedOption == "Analyze Image" or selectedOption == "Extract Text Only" or selectedOption == "Translate Image Text" or selectedOption == "Summarize Document" then
            if selectedPhotoPath == "" and not selectedPhotoUri then
                vibratePattern("error")
                notify("Please select an image first")
                processButton.setEnabled(true); processButton.setText("Process"); processButton.setBackgroundColor(0xFFFF9800)
                return
            end
            local apiKey = getGeminiApiKey()
            if not apiKey or apiKey == "" then
                vibratePattern("error")
                notify("API Key missing! Set in Settings")
                processButton.setEnabled(true); processButton.setText("Process"); processButton.setBackgroundColor(0xFFFF9800)
                return
            end

            -- انٹرنیٹ چیک: نہ ہونے کی صورت میں صرف "Extract Text Only" کے لیے
            -- آفلائن OCR آزمائی جاتی ہے، باقی موڈز کو AI reasoning کی وجہ سے
            -- لازمی انٹرنیٹ چاہیے ہوتا ہے۔
            if not isNetworkAvailable() then
                if selectedOption == "Extract Text Only" then
                    showProgress("انٹرنیٹ نہیں ملا — Offline OCR آزمایا جا رہا ہے...")
                    tryOfflineOCR(function(res, err)
                        hideProgress()
                        if res then
                            showResultDialog("Offline OCR Result", res)
                            saveHistoryEntry("Extract Text Only (Offline)", res)
                            vibratePattern("success")
                        else
                            vibratePattern("error")
                            notify(err or "Offline OCR failed")
                        end
                        processButton.setEnabled(true); processButton.setText("Process"); processButton.setBackgroundColor(0xFFFF9800)
                    end)
                else
                    vibratePattern("error")
                    notify("انٹرنیٹ کنکشن نہیں ہے۔ اس موڈ کے لیے انٹرنیٹ ضروری ہے۔")
                    processButton.setEnabled(true); processButton.setText("Process"); processButton.setBackgroundColor(0xFFFF9800)
                end
                return
            end
            
            showProgress("Processing image with " .. getGeminiModel() .. "...")
            
            local base64Data = getSelectedImageBase64()
            if not base64Data then
                hideProgress()
                vibratePattern("error")
                notify("Failed to process image. It might be deleted or unavailable.")
                processButton.setEnabled(true); processButton.setText("Process"); processButton.setBackgroundColor(0xFFFF9800)
                return
            end
            
