function hasRecordAudioPermission()
    local ok, result = pcall(function()
        return ctx.checkSelfPermission(Manifest.permission.RECORD_AUDIO) == PackageManager.PERMISSION_GRANTED
    end)
    if ok then return result end
    return true -- چیک ناکام ہونے کی صورت میں کوشش کرنے دیں، اصل ایرر SpeechRecognizer خود دے دے گا
end

-- بولے گئے سوال کو سنتا ہے۔ اگر منتخب زبان آواز-شناخت کے لیے سپورٹڈ نہ
-- ہو (ایرر 12/13)، تو خودکار طور پر ڈیوائس کی ڈیفالٹ زبان کے ساتھ ایک
-- بار دوبارہ کوشش کرتا ہے — تاکہ صارف کو صرف "کام نہیں کر رہا" کے
-- بجائے کوئی نتیجہ ملے۔
function askQuestionInLiveMode(statusTv, useDeviceDefaultLocale, attemptNumber)
    attemptNumber = attemptNumber or 1

    if not hasRecordAudioPermission() then
        vibratePattern("error")
        notify("Microphone پرمیشن نہیں ملی۔ براہِ کرم App Settings میں جا کر Microphone پرمیشن آن کریں۔")
        return
    end

    -- سوال شروع ہوتے ہی خودکار تفصیل اور فون کی بولتی آواز روک دیں، ورنہ مائیک
    -- فون کی اپنی آواز سن کر "سمجھ نہیں آئی" دیتا تھا اور جواب کٹ جاتے تھے
    local listenDelayMs = 0
    if attemptNumber == 1 then
        pauseLiveAuto(60)
        pcall(stopTTS)
        pcall(function()
            if service then
                if service.stopSpeak then service.stopSpeak()
                elseif service.stopSpeaking then service.stopSpeaking()
                elseif service.stop then service.stop() end
            end
        end)
        -- اگر ابھی ابھی کچھ بولا گیا ہو تو اس کے ختم ہونے کا تھوڑا انتظار
        if os.time() - (liveModeState.lastSpokeAt or 0) <= 3 then listenDelayMs = 1500 end
    end

    -- SpeechRecognizer کو ہمیشہ Main/UI Thread (جس کا اپنا Looper ہو) پر
    -- ہی بنانا اور چلانا ضروری ہے — بصورتِ دیگر یہ خاموشی سے ناکام ہو
    -- جاتا ہے۔ چونکہ ہمیں یقین نہیں کہ بٹن کلک کس تھریڈ پر آتا ہے، اسے
    -- جبراً Main Looper پر بھیجا جا رہا ہے۔
    local handler = Handler(Looper.getMainLooper())
    handler.postDelayed(Runnable({ run = function()
        local ok, err = pcall(function()
            if not SpeechRecognizer.isRecognitionAvailable(ctx) then
                error("Speech recognition not available on this device")
            end

            local recognizer = SpeechRecognizer.createSpeechRecognizer(ctx)
            if not recognizer then
                error("SpeechRecognizer.createSpeechRecognizer returned nil")
            end

            local recIntent = Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH)
            recIntent.putExtra(RecognizerIntent.EXTRA_LANGUAGE_MODEL, RecognizerIntent.LANGUAGE_MODEL_FREE_FORM)
            recIntent.putExtra(RecognizerIntent.EXTRA_PARTIAL_RESULTS, true)
            recIntent.putExtra(RecognizerIntent.EXTRA_MAX_RESULTS, 3)
            -- زیادہ وقت دیں تاکہ بولتے ہوئے جلدی نہ کٹے
            pcall(function() recIntent.putExtra("android.speech.extra.SPEECH_INPUT_COMPLETE_SILENCE_LENGTH_MILLIS", 1800) end)
            pcall(function() recIntent.putExtra("android.speech.extra.SPEECH_INPUT_POSSIBLY_COMPLETE_SILENCE_LENGTH_MILLIS", 1800) end)
            pcall(function() recIntent.putExtra("android.speech.extra.SPEECH_INPUT_MINIMUM_LENGTH_MILLIS", 15000) end)

            if not useDeviceDefaultLocale then
                local localeInfo = LANGUAGE_TO_LOCALE[getSelectedLanguage()] or LANGUAGE_TO_LOCALE["English"]
                recIntent.putExtra(RecognizerIntent.EXTRA_LANGUAGE, localeInfo[1] .. "-" .. localeInfo[2])
            end

            recognizer.setRecognitionListener(RecognitionListener{
            onReadyForSpeech = function(params)
                if statusTv then pcall(function() statusTv.setText("🎤 سنیے... اب بولیں") end) end
            end,
            onBeginningOfSpeech = function()
                if statusTv then pcall(function() statusTv.setText("🎤 سن رہا ہوں...") end) end
            end,
            onRmsChanged = function(rmsdB) end,
            onBufferReceived = function(buffer) end,
            onEndOfSpeech = function()
                if statusTv then pcall(function() statusTv.setText("سوچ رہا ہوں...") end) end
            end,
            onResults = function(results)
                local ok2, err2 = pcall(function()
                    local matches = results.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
                    if matches and matches.size() > 0 then
                        local question = matches.get(0)
                        logInfo("Voice question recognized: " .. tostring(question))
                        askAIFollowUp(question, statusTv)
                    else
                        vibratePattern("error")
                        pauseLiveAuto(0)
                        notify("کچھ سمجھ نہیں آیا، دوبارہ کوشش کریں")
                    end
                end)
                if not ok2 then logError("onResults handling failed: " .. tostring(err2)) end
                pcall(function() recognizer.destroy() end)
            end,
            onError = function(errorCode)
                logWarn("SpeechRecognizer error code: " .. tostring(errorCode))
                pcall(function() recognizer.destroy() end)

                -- اگر منتخب زبان آواز شناخت کے لیے سپورٹڈ نہیں (12/13) تو ڈیوائس
                -- کی ڈیفالٹ زبان کے ساتھ خودکار طور پر ایک بار دوبارہ کوشش کریں
                if (errorCode == 12 or errorCode == 13) and attemptNumber == 1 and not useDeviceDefaultLocale then
                    logInfo("Retrying speech recognition with device default locale.")
                    if statusTv then pcall(function() statusTv.setText("اس زبان میں آواز شناخت دستیاب نہیں — ڈیوائس کی ڈیفالٹ زبان سے دوبارہ کوشش ہو رہی ہے...") end) end
                    askQuestionInLiveMode(statusTv, true, 2)
                elseif (errorCode == 6 or errorCode == 7) and attemptNumber == 1 then
                    -- کچھ سنائی نہیں دیا: ایک بار خودکار طور پر دوبارہ سننے کی کوشش
                    if statusTv then pcall(function() statusTv.setText("آواز سنائی نہیں دی — دوبارہ بولیں...") end) end
                    vibratePattern("notify")
                    askQuestionInLiveMode(statusTv, useDeviceDefaultLocale, 2)
                else
                    pauseLiveAuto(0)
                    vibratePattern("error")
                    -- خرابی کا صاف مطلب + اصل کوڈ، دونوں دکھائیں (بگ رپورٹ کرنا آسان ہو)
                    notify(describeSpeechError(errorCode) .. " [code:" .. tostring(errorCode) .. "]")
                    if statusTv then pcall(function() statusTv.setText(describeSpeechError(errorCode) .. " (error code " .. tostring(errorCode) .. ")") end) end
                end
            end,
            onPartialResults = function(partialResults)
                local ok3, question = pcall(function()
                    local matches = partialResults.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
                    if matches and matches.size() > 0 then return matches.get(0) end
                    return nil
                end)
                if ok3 and question and statusTv then
                    pcall(function() statusTv.setText("🎤 " .. question) end)
                end
            end,
            onEvent = function(eventType, params) end
        })

            recognizer.startListening(recIntent)
        end)

        if not ok then
            logError("askQuestionInLiveMode failed: " .. tostring(err))
            vibratePattern("error")
            pauseLiveAuto(0)
            notify("Voice سوال شروع نہیں ہو سکا — تفصیل: " .. tostring(err))
            if statusTv then pcall(function() statusTv.setText("Voice error: " .. tostring(err)) end) end
        end
    end }), listenDelayMs)
end

function startLiveMode()
    if liveModeState.active then
        notify("Live Mode پہلے سے چل رہا ہے")
        return
    end
    if mainDlg then mainDlg.dismiss() mainDlg = nil end

