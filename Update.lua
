-- الگ الگ حالتوں کے لیے مختلف Vibration پیٹرنز (بصارت سے محروم صارف کے لیے
-- اسکرین دیکھے بغیر سمجھنا آسان ہو جاتا ہے کہ کیا ہو رہا ہے)
--   success    -> ایک مختصر، ہلکا سا جھٹکا
--   error      -> تین تیز جھٹکے (واضح طور پر الگ محسوس ہوں)
--   processing -> دو ہلکے مختصر جھٹکے
--   notify     -> عام مختصر جھٹکا (پرانے vibrate() جیسا)
function vibratePattern(kind)
    local vibrator = ctx.getSystemService(Context.VIBRATOR_SERVICE)
    if not vibrator then return end

    local patterns = {
        success    = { {90, 0} },
        error      = { {120, 80}, {120, 80}, {120, 0} },
        processing = { {40, 60}, {40, 0} },
        notify     = { {35, 0} }
    }
    local steps = patterns[kind] or patterns.notify

    local function runStep(i)
        if i > #steps then return end
        local step = steps[i]
        pcall(function() vibrator.vibrate(step[1]) end)
        if step[2] and step[2] > 0 then
            local handler = Handler(Looper.getMainLooper())
            handler.postDelayed(Runnable({ run = function() runStep(i + 1) end }), step[1] + step[2])
        end
    end
    runStep(1)
end

