end

function importSettingsFromJSON(jsonText)
    local ok, data = pcall(cjson.decode, jsonText)
    if not ok or type(data) ~= "table" then
        return false, "JSON پڑھنے میں مسئلہ ہوا — متن درست نہیں۔"
    end
    pcall(function()
        if data.groq_apiKey then saveAIApiKey(data.groq_apiKey) end
        if data.groq_model and aiApiDetails[data.groq_model] then saveAIModel(data.groq_model) end
        if data.selected_language then saveSelectedLanguage(data.selected_language) end
        if data.rec_option then saveSelectedRecognizeOption(data.rec_option) end
        if data.live_interval_sec then saveLiveModeIntervalSeconds(data.live_interval_sec) end
        if data.speech_rate then saveSpeechRate(data.speech_rate) end
        if data.speech_pitch then saveSpeechPitch(data.speech_pitch) end
        if data.tts_engine_pkg then saveTTSEnginePackage(data.tts_engine_pkg) end
        if data.tts_voice_name then saveTTSVoiceName(data.tts_voice_name) end
        if data.custom_prompts then
            for modeKey, _ in pairs(CUSTOM_PROMPT_KEYS) do
                if data.custom_prompts[modeKey] then
                    saveCustomPrompt(modeKey, data.custom_prompts[modeKey])
                end
            end
        end
    end)
    return true, nil
end

-- ڈیوائس پر Downloads/CSR_AI_Assistant فولڈر میں بیک اپ زپ فائل کے لیے
-- ایک نئی content:// URI بناتا ہے (MediaStore کے ذریعے — کوئی
-- FileProvider/Manifest تبدیلی درکار نہیں، نہ ہی کریش کا خطرہ)
function createBackupOutputUri()
    local ok, result = pcall(function()
        local values = ContentValues()
        values.put(MediaStore.MediaColumns.DISPLAY_NAME, CONFIG.BACKUP_FILE_NAME)
        values.put(MediaStore.MediaColumns.MIME_TYPE, "application/zip")
        pcall(function() values.put(MediaStore.MediaColumns.RELATIVE_PATH, "Download/CSR_AI_Assistant") end)
        local resolver = ctx.getContentResolver()
        return resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
    end)
    if ok and result then return result end
    logError("createBackupOutputUri failed: " .. tostring(result))
    return nil
end

-- موجودہ ترتیبات کو ایک .zip فائل کے طور پر Downloads/CSR_AI_Assistant
-- میں محفوظ کرتا ہے — File Manager سے نظر آئے گی اور کسی دوسرے ڈیوائس
-- پر کاپی کی جا سکتی ہے۔
function exportSettingsToZipFile()
    local json = exportSettingsAsJSON()
    if not json then return nil, "Settings ایکسپورٹ نہیں ہو سکیں" end

    local outputUri = createBackupOutputUri()
    if not outputUri then return nil, "بیک اپ فائل نہیں بن سکی (Storage پرمیشن چیک کریں)" end

    local ok, err = pcall(function()
        local resolver = ctx.getContentResolver()
        local outStream = resolver.openOutputStream(outputUri)
        local zipOut = ZipOutputStream(outStream)
        zipOut.putNextEntry(ZipEntry("settings.json"))
        for i = 1, #json do
            zipOut.write(string.byte(json, i))
        end
        zipOut.closeEntry()
        zipOut.close()
    end)
    if not ok then
        logError("exportSettingsToZipFile failed: " .. tostring(err))
        return nil, "بیک اپ فائل لکھنے میں مسئلہ ہوا: " .. tostring(err)
    end
    logInfo("Settings backed up to Downloads/CSR_AI_Assistant/" .. CONFIG.BACKUP_FILE_NAME)
    return outputUri, nil
end

-- Downloads میں پہلے سے بنی بیک اپ زپ فائل تلاش کرتا ہے
function findBackupFileUri()
    local ok, result = pcall(function()
        local resolver = ctx.getContentResolver()
        local projection = { MediaStore.MediaColumns._ID }
        local selection = MediaStore.MediaColumns.DISPLAY_NAME .. " = ?"
        local selectionArgs = { CONFIG.BACKUP_FILE_NAME }
        local cursor = resolver.query(MediaStore.Downloads.EXTERNAL_CONTENT_URI, projection, selection, selectionArgs, nil)
        local foundUri = nil
        if cursor and cursor.moveToFirst() then
            local idCol = cursor.getColumnIndexOrThrow(MediaStore.MediaColumns._ID)
            local id = cursor.getLong(idCol)
            foundUri = Uri.withAppendedPath(MediaStore.Downloads.EXTERNAL_CONTENT_URI, tostring(id))
        end
        if cursor then cursor.close() end
        return foundUri
    end)
    if ok then return result end
    logError("findBackupFileUri failed: " .. tostring(result))
    return nil
end

-- Downloads/CSR_AI_Assistant میں موجود بیک اپ زپ فائل سے ترتیبات واپس لاگو کرتا ہے
function importSettingsFromZipFile()
    local uri = findBackupFileUri()
    if not uri then
        return false, "بیک اپ فائل نہیں ملی۔ یقینی بنائیں کہ 'Download/CSR_AI_Assistant/" .. CONFIG.BACKUP_FILE_NAME .. "' موجود ہے (دوسرے ڈیوائس سے کاپی کی ہو تو اسی جگہ رکھیں)۔"
    end

    local ok, jsonOrErr = pcall(function()
        local resolver = ctx.getContentResolver()
        local inStream = resolver.openInputStream(uri)
        local zipIn = ZipInputStream(inStream)
        local entry = zipIn.getNextEntry()
        local jsonChars = {}
        local found = false
        while entry ~= nil do
            if tostring(entry.getName()) == "settings.json" then
                found = true
                local b = zipIn.read()
                while b ~= -1 do
                    table.insert(jsonChars, string.char(b))
                    b = zipIn.read()
                end
            end
            pcall(function() zipIn.closeEntry() end)
            entry = zipIn.getNextEntry()
        end
        zipIn.close()
        if not found then error("settings.json entry not found in zip") end
        return table.concat(jsonChars)
    end)

    if not ok then
        logError("importSettingsFromZipFile read failed: " .. tostring(jsonOrErr))
        return false, "بیک اپ فائل پڑھنے میں مسئلہ ہوا — فائل خراب یا غلط فارمیٹ کی ہو سکتی ہے۔"
    end
    return importSettingsFromJSON(jsonOrErr)
end

