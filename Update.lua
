function askAIFollowUp(question, statusTv)
    local apiKey = getAIApiKey()
    if not apiKey or apiKey == "" then
        notify("API Key missing! پہلے Settings میں سیٹ کریں")
        pauseLiveAuto(0)
        return
    end

    vibratePattern("processing")
    if statusTv then pcall(function() statusTv.setText("Q: " .. question .. "\n\nسوچ رہا ہوں...") end) end
    local lang = getSelectedLanguage()

    -- سوال پوچھنے کے لمحے کا تازہ فریم لیں؛ نہ ملے تو پچھلا؛ وہ بھی نہ ہو تو صرف متن سے جواب دیں
    captureFreshFrame(function(freshFrame)
        local image = freshFrame or liveModeState.lastFrameBase64
        local custom = getCustomPrompt("qa")
        local basePrompt
        if custom ~= "" then
            basePrompt = custom .. " The user just asked, by voice: \"" .. question .. "\"."
        else
            basePrompt = "You are a helpful, knowledgeable voice assistant for a visually impaired user, talking with them by voice. They just asked, by voice: \"" .. question .. "\". " ..
                "If their question relates to what is currently visible in the attached camera image, use the image to answer accurately. " ..
                "If it is a general question unrelated to the image (facts, advice, explanations, calculations, definitions, translations, how-to help, conversation, or anything else), just answer it directly and helpfully like a normal AI assistant would — do not force a connection to the image. " ..
                "Give a clear, complete, natural-sounding spoken answer (a few sentences if needed, as long as it fully answers the question)."
        end
        if not image then
            basePrompt = basePrompt .. " (No camera image is available right now, so answer from general knowledge.)"
        end
        local prompt = basePrompt .. " IMPORTANT: your entire reply must be written ONLY in " .. lang .. ". Do not use English or any other language, not even a single word, unless " .. lang .. " itself is English."

        callAIWithImage(apiKey, getAIModel(), image, prompt, function(res, err)
            if res then
                if statusTv then pcall(function() statusTv.setText("Q: " .. question .. "\n\nA: " .. res) end) end
                speakInSelectedLanguage(res)
                liveModeState.lastSpokeAt = os.time()
                -- جواب بولے جانے کے دوران خودکار تفصیل رکی رہے (تقریباً بولنے کے وقت کے برابر)
                local est = math.max(6, math.ceil(#res / 18))
                if getSpeechRate() < 1 then est = math.ceil(est * 1.4) end
                pauseLiveAuto(est + 2)
                saveHistoryEntry("Live Q&A (" .. lang .. ")", question .. " → " .. res)
            else
                logError("Live Q&A error: " .. tostring(err))
                vibratePattern("error")
                if statusTv then pcall(function() statusTv.setText("⚠️ " .. tostring(err)) end) end
                notify("جواب نہیں مل سکا: " .. tostring(err))
                pauseLiveAuto(0)
            end
        end, { maxTokens = 700, noCache = true })
    end)
end

