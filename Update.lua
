-- ماڈل کی سوچ والے حصے (<think>...</think>) اگر آ جائیں تو ہٹا دیے جاتے ہیں
local function extractAIText(decoded)
    if type(decoded.choices) == "table" and decoded.choices[1] and type(decoded.choices[1].message) == "table" then
        local m = decoded.choices[1].message.content
        if type(m) == "string" then
            m = m:gsub("<think>.-</think>", "")
            m = m:gsub("^%s+", ""):gsub("%s+$", "")
            if m ~= "" then return m end
        end
    end
    return nil
end

-- ایک ہی کوشش (attempt) کے لیے Groq کو HTTP کال
-- onDone(text, errorMessage, retryable, httpStatus)
local function attemptAICall(apiKey, payload, attemptNumber, model, onDone)
    local headers = {
        ["Content-Type"] = "application/json",
        ["Authorization"] = "Bearer " .. tostring(apiKey)
    }
    local ok, err = pcall(function()
        Http.post(AI_API_URL, cjson.encode(payload), headers, function(status, data)
            status = tonumber(status) or 0
            if status == 200 then
                local decodeOk, decoded = pcall(cjson.decode, data)
                if decodeOk and type(decoded) == "table" then
                    local text = extractAIText(decoded)
                    if text then
                        pcall(function() recordTokenUsage(decoded.usage) end)
                        onDone(text, nil, false, 200)
                    else
                        local finish = nil
                        pcall(function() finish = decoded.choices[1].finish_reason end)
                        if finish == "length" then
                            onDone(nil, "جواب نامکمل رہا (ماڈل نے حد پار کر لی)۔ دوبارہ کوشش کریں۔", true, 200)
                        else
                            onDone(nil, "AI نے کوئی متن واپس نہیں کیا (ہو سکتا ہے سیفٹی فلٹر نے روک دیا ہو)۔", false, 200)
                        end
                    end
                else
                    onDone(nil, "AI کا جواب درست فارمیٹ میں نہیں آیا۔", true, 200)
                end
            elseif status == 400 then
                local msg = extractAIErrorMessage(data)
                onDone(nil, "Error 400 (درخواست درست نہیں): " .. tostring(msg or "تفصیل دستیاب نہیں"), false, 400)
            elseif status == 401 or status == 403 then
                local msg = extractAIErrorMessage(data)
                onDone(nil, "Error " .. status .. ": API Key غلط ہے یا اجازت نہیں۔ Settings میں Groq key (gsk_ سے شروع ہونے والی) چیک کریں۔ " .. tostring(msg or ""), false, status)
            elseif status == 404 then
                onDone(nil, "Error 404: منتخب ماڈل (" .. model .. ") دستیاب نہیں۔ Settings میں کوئی اور ماڈل منتخب کریں۔", false, 404)
            elseif status == 413 then
                onDone(nil, "Error 413: تصویر/درخواست بہت بڑی ہے۔", false, 413)
            elseif status == 408 or status == 429 then
                local msg = extractAIErrorMessage(data)
                onDone(nil, "Error " .. status .. ": Rate limit (مفت پلان کی حد) یا وقت ختم۔ تھوڑی دیر بعد دوبارہ کوشش کریں۔ " .. tostring(msg or ""), true, status)
            elseif status >= 500 then
                onDone(nil, "Server Error " .. status .. ": Groq سروس عارضی طور پر دستیاب نہیں۔", true, status)
            elseif status == 0 or status < 0 then
                onDone(nil, "انٹرنیٹ/نیٹ ورک کا مسئلہ — سرور تک رسائی نہیں ہوئی۔", true, 0)
            else
                local msg = extractAIErrorMessage(data)
                onDone(nil, "API Error " .. status .. ": " .. tostring(msg or ""), false, status)
            end
        end)
    end)
    if not ok then
        logError("attemptAICall pcall failed: " .. tostring(err))
        onDone(nil, "Network/Runtime error while calling API: " .. tostring(err), true, 0)
    end
end

-- =====================================================================
-- RESPONSE CACHE — اگر بالکل وہی تصویر، وہی موڈ اور وہی ماڈل دوبارہ
-- پروسیس کی جائے (مثلاً Batch میں غلطی سے دو بار، یا دوبارہ تصویر
-- منتخب کرنے پر)، تو نیا API کال کرنے کے بجائے محفوظ شدہ جواب فوراً
-- واپس کر دیا جاتا ہے — وقت اور Tokens دونوں بچتے ہیں۔
-- =====================================================================
local RESPONSE_CACHE_FILE_NAME = "CSR_AI_Assistant_Cache.json"
local RESPONSE_CACHE_MAX_ENTRIES = 30

function simpleHash(str)
    if not str then return "0_0" end
    local hash = 5381
    local len = #str
    local step = math.max(1, math.floor(len / 2000))
    for i = 1, len, step do
        hash = (hash * 33 + string.byte(str, i)) % 2147483647
    end
    return tostring(hash) .. "_" .. tostring(len)
end

function getResponseCacheFilePath()
    return (os.getenv("EXTERNAL_STORAGE") or "/sdcard") .. "/" .. RESPONSE_CACHE_FILE_NAME
end

function loadResponseCache()
    local ok, result = pcall(function()
        local f = io.open(getResponseCacheFilePath(), "r")
        if not f then return {} end
        local content = f:read("*a")
        f:close()
        if not content or content == "" then return {} end
        local decodeOk, decoded = pcall(cjson.decode, content)
        if decodeOk and type(decoded) == "table" then return decoded end
        return {}
    end)
    if ok then return result end
    return {}
end

function getCachedResponse(key)
    local ok, cache = pcall(loadResponseCache)
    if ok and cache and cache[key] then return cache[key].text end
    return nil
end

function setCachedResponse(key, text)
    pcall(function()
        local cache = loadResponseCache()
        cache[key] = { text = text, time = os.time() }
        local count = 0
        for _ in pairs(cache) do count = count + 1 end
        if count > RESPONSE_CACHE_MAX_ENTRIES then
            local entries = {}
            for k, v in pairs(cache) do table.insert(entries, {k = k, time = v.time or 0}) end
            table.sort(entries, function(a, b) return a.time < b.time end)
            local toRemove = count - RESPONSE_CACHE_MAX_ENTRIES
            for i = 1, toRemove do cache[entries[i].k] = nil end
        end
        local f = io.open(getResponseCacheFilePath(), "w")
        if f then
            f:write(cjson.encode(cache))
            f:close()
        end
    end)
end

-- عوامی فنکشن: خودکار ری-ٹرائی اور Safe Mode کے ساتھ Groq کو امیج بھیجنا
-- opts.maxTokens: جواب کی زیادہ سے زیادہ لمبائی (Live Mode میں چھوٹی رکھی جاتی ہے)
function callAIWithImage(apiKey, model, base64Data, prompt, callback, opts)
    opts = opts or {}
    local maxTokens = opts.maxTokens or 1500

    if runtimeState.safeModeActive then
        -- Safe Mode خود بخود 60 سیکنڈ بعد ختم ہو جاتا ہے (پہلے یہ ہمیشہ کے لیے بلاک کر دیتا تھا)
        if os.time() - (runtimeState.safeModeSince or 0) >= 60 then
            runtimeState.safeModeActive = false
            runtimeState.consecutiveFailures = 0
            logInfo("Safe Mode expired automatically after 60 seconds.")
        else
            logWarn("callAIWithImage blocked: Safe Mode is active.")
            callback(nil, "Safe Mode فعال ہے۔ بار بار ایرر کی وجہ سے AI عارضی طور پر (تقریباً ایک منٹ کے لیے) بند ہے۔ تھوڑی دیر بعد دوبارہ کوشش کریں۔")
            return
        end
    end

    -- Live Mode/Voice Q&A میں ہر فریم نیا ہوتا ہے، اس لیے کیش (فائل پڑھنا/لکھنا) صرف وقت ضائع کرتا ہے
    local cacheKey = nil
    if not opts.noCache and base64Data then
        cacheKey = simpleHash(base64Data .. "|" .. model .. "|" .. prompt)
        local cachedText = getCachedResponse(cacheKey)
        if cachedText then
            logInfo("Response cache hit — skipping API call.")
            callback(cachedText, nil)
            return
        end
    end

    local modelInfo = aiApiDetails[model]
    if not modelInfo then
        logError("callAIWithImage: invalid model '" .. tostring(model) .. "'")
        callback(nil, "غلط ماڈل منتخب ہے — Settings میں کوئی Qwen ماڈل منتخب کریں۔")
        return
    end

    -- base64Data نہ ہو تو صرف متن بھیجا جاتا ہے (Voice Q&A میں فریم نہ ملے تب بھی جواب ملے)
    local contentParts = { { type = "text", text = prompt } }
    if base64Data then
        table.insert(contentParts, { type = "image_url", image_url = { url = "data:image/jpeg;base64," .. base64Data } })
    end
    local payload = {
        model = modelInfo.id,
        messages = {{
            role = "user",
            content = contentParts
        }},
        max_completion_tokens = maxTokens,
        stream = false
    }
    -- سوچنے (reasoning) کو بند رکھنے سے جواب بہت تیز آتا ہے (Live Mode کے لیے ضروری)
    if CONFIG.REASONING_EFFORT and CONFIG.REASONING_EFFORT ~= "" then
        payload.reasoning_effort = CONFIG.REASONING_EFFORT
    end

    logInfo("Calling Groq model=" .. modelInfo.id)

    local function tryAttempt(attemptNumber)
        attemptAICall(apiKey, payload, attemptNumber, model, function(result, errMsg, retryable, httpStatus)
            if result then
                logInfo("Groq call succeeded on attempt " .. attemptNumber)
                resetFailureState()
                if cacheKey then setCachedResponse(cacheKey, result) end
                callback(result, nil)
                return
            end

            logError("Groq call failed (attempt " .. attemptNumber .. "): " .. tostring(errMsg))

            -- اگر ماڈل reasoning_effort کی قدر قبول نہ کرے (400) تو اسے ہٹا کر
            -- فوراً ایک بار دوبارہ کوشش کریں (صارف کو ایرر دکھائے بغیر)
            if httpStatus == 400 and payload.reasoning_effort and string.find(string.lower(tostring(errMsg)), "reasoning", 1, true) then
                logWarn("Model rejected reasoning_effort — retrying without it.")
                payload.reasoning_effort = nil
                tryAttempt(attemptNumber)
                return
            end

            if retryable and attemptNumber <= CONFIG.MAX_RETRIES then
                local handler = Handler(Looper.getMainLooper())
                handler.postDelayed(Runnable({ run = function()
                    tryAttempt(attemptNumber + 1)
                end }), CONFIG.RETRY_DELAY_MS)
            else
                -- صرف سرور/نیٹ ورک کی خرابیاں Safe Mode کی طرف گنی جاتی ہیں؛
                -- غلط key/ماڈل جیسی ترتیب کی غلطیاں نہیں
                if retryable then enterSafeModeIfNeeded() end
                callback(nil, errMsg)
            end
        end)
    end

    tryAttempt(1)
end

