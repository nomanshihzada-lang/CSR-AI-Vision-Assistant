-- Voice Q&A کے دوران خودکار تفصیل روک دیتا ہے تاکہ مائیک خود فون کی آواز نہ
-- سنے اور سوال کا جواب نئی خودکار تفصیل سے کٹ نہ جائے
function pauseLiveAuto(seconds)
    liveModeState.pausedUntil = os.time() + seconds
