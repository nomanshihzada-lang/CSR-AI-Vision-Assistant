    btnAsk.setTextColor(0xFFFFFFFF)
    btnAsk.onClick = function() askQuestionInLiveMode(statusTv) end
    liveLayout.addView(btnAsk)

    local liveDlg = LuaDialog(ctx)
    liveDlg.setTitle("Live Navigation Mode — " .. getSelectedLanguage() .. " (every " .. (getLiveModeIntervalSeconds()) .. "s)")
    liveDlg.setView(liveLayout)
    liveDlg.setCancelable(false)
    liveDlg.setNegativeButton("Stop", function()
        stopLiveMode()
        notify("Live Mode بند کر دیا گیا")
        createMainUI()
    end)
    liveDlg.show()

    local holder = surfaceView.getHolder()
    holder.addCallback(SurfaceHolder.Callback{
        surfaceCreated = function(h)
            local ok, err = pcall(function()
                liveModeState.camera = Camera.open()

                -- فریم چھوٹے (≤800x600) رکھیں تاکہ اپلوڈ اور جواب تیز ہو، اور
                -- مسلسل فوکس لگائیں تاکہ تصویر دھندلی نہ آئے
                pcall(function()
                    local cam = liveModeState.camera
                    local params = cam.getParameters()
                    local sizes = params.getSupportedPreviewSizes()
                    local bestW, bestH, bestArea = nil, nil, 0
                    for i = 0, sizes.size() - 1 do
                        local sz = sizes.get(i)
                        local w, h = sz.width, sz.height
                        if w <= 800 and h <= 600 and (w * h) > bestArea then
                            bestW, bestH, bestArea = w, h, w * h
                        end
                    end
                    if bestW then params.setPreviewSize(bestW, bestH) end
                    pcall(function()
                        local modes = params.getSupportedFocusModes()
                        if modes and modes.contains("continuous-picture") then
                            params.setFocusMode("continuous-picture")
                        end
                    end)
                    cam.setParameters(params)
                end)
                pcall(function() liveModeState.camera.setDisplayOrientation(getCameraRotation()) end)

                liveModeState.camera.setPreviewDisplay(h)
                liveModeState.camera.startPreview()
                liveModeState.active = true
                liveModeState.busy = false
                liveModeState.pausedUntil = 0
                statusTv.setText("Live Mode active — جلد پہلی تفصیل آ رہی ہے...")
                logInfo("Live Mode camera started.")

                -- پہلا کیپچر 1.2 سیکنڈ بعد؛ اس کے بعد ہر جواب مکمل ہونے کے "وقفے" بعد
                -- اگلا (پہلے ہر وقفے پر ایک ساتھ کیپچر ہوتا تھا اور پہلا جواب بہت دیر سے آتا تھا)
                local loopHandler = Handler(Looper.getMainLooper())
                local function scheduleNextCapture(delayMs)
                    if not liveModeState.active then return end
                    loopHandler.postDelayed(Runnable({ run = function()
                        if not liveModeState.active or not liveModeState.camera then return end
                        if liveModeState.busy or os.time() < liveModeState.pausedUntil then
                            scheduleNextCapture(1000)
                            return
                        end
                        liveModeState.busy = true
                        captureFreshFrame(function(b64)
                            if b64 and liveModeState.active then
                                processLiveFrame(b64, statusTv, function()
                                    scheduleNextCapture(getLiveModeIntervalSeconds() * 1000)
                                end)
                            else
                                liveModeState.busy = false
                                scheduleNextCapture(1500)
                            end
                        end)
                    end }), delayMs)
                end
                scheduleNextCapture(1200)
            end)
            if not ok then
                logError("Live Mode camera failed to start: " .. tostring(err))
                statusTv.setText("Camera دستیاب نہیں۔ App Settings میں جا کر Camera permission دیں اور دوبارہ کوشش کریں۔")
                notify("Camera access failed. براہ کرم App Settings میں Camera permission چیک کریں۔")
            end
        end,
        surfaceChanged = function(h, format, w, hgt) end,
        surfaceDestroyed = function(h) stopLiveMode() end
    })
end

