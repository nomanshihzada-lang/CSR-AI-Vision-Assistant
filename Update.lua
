                if kind == "document" then pcall(notify, "Document Reader. Hold the phone above the page.") end
                if kind == "find" then pcall(notify, "Looking for " .. tostring(profile.target or "") .. ". Turn slowly.") end

                -- Camera Mode میں خودکار لوپ نہیں؛ صرف Capture بٹن سے تصویر لی جاتی ہے
                if kind == "camera" then return end

                local frameHandler = processLiveFrame
                if kind == "document" then frameHandler = processDocumentFrame end

                -- پہلا کیپچر 1.2 سیکنڈ بعد؛ اس کے بعد ہر جواب مکمل ہونے کے "وقفے" بعد اگلا
                local loopHandler = Handler(Looper.getMainLooper())
                local function scheduleNextCapture(delayMs)
                    if not liveModeState.active then return end
                    loopHandler.postDelayed(Runnable({ run = guard("run (camera loop)", function()
                        if not liveModeState.active or not liveModeState.camera then return end
                        if liveModeState.busy or os.time() < liveModeState.pausedUntil or os.time() < (liveModeState.rateLimitedUntil or 0) then
                            scheduleNextCapture(1000)
                            return
                        end
                        -- Groq کی مفت حد کے اندر رہنے کے لیے ضرورت ہو تو انتظار (ہر تصویر ~2200 ان پُٹ ٹوکن)
                        local lastIn = 0
                        pcall(function()
                            local w = runtimeState.tokenWindow
                            if w and #w > 0 then lastIn = w[#w].input or 0 end
                        end)
                        local budgetWait = secondsUntilBudget(math.max(2400, lastIn), 150)
                        if budgetWait > 0 then
                            pcall(function() statusTv.setText("Waiting about " .. formatDuration(budgetWait) .. " to stay inside Groq's free limit...") end)
                            scheduleNextCapture(math.floor(budgetWait * 1000))
                            return
                        end
                        liveModeState.busy = true
                        captureFreshFrame(function(b64)
                            if b64 and liveModeState.active then
                                frameHandler(b64, statusTv, function()
                                    -- منظر نہ بدلے تو چیک کا وقفہ بڑھتا ہے (زیادہ سے زیادہ 3 گنا): کم درخواستیں، کم 429
                                    local streak = math.min(liveModeState.unchangedStreak or 0, 2)
                                    scheduleNextCapture(getLiveModeIntervalSeconds() * 1000 * (1 + streak))
                                end)
                            else
                                liveModeState.busy = false
                                scheduleNextCapture(1500)
                            end
                        end)
                    end) }), delayMs)
                end
                scheduleNextCapture(1200)
            end)
            if not ok then
                logError("Camera screen failed to start: " .. tostring(err))
                pcall(reportError, "Camera screen (" .. kind .. ")", tostring(err))
                statusTv.setText("The camera is not available. Check the Camera permission in App Settings and try again.")
                notify("Camera access failed. Please check the Camera permission in App Settings.")
            end
        end),
        surfaceChanged = function(h, format, w, hgt) end,
        surfaceDestroyed = function(h) stopLiveMode() end
    })
end

-- Share پر کلک کرتے ہی ایپ کی تمام کھلی ونڈوز (مین اسکرین، سیٹنگز، لائیو موڈ وغیرہ)
-- بند کر کے شیئر شیٹ کھولتا ہے، تاکہ ایپ "بند" ہو جائے اور شیئر شیٹ کے پیچھے
-- پرانی ونڈوز نہ رہیں۔ dialogsToClose: وہ ڈائیلاگ جو اس وقت کھلے ہیں
function shareTextAndCloseApp(text, subject, chooserTitle, dialogsToClose)
    if dialogsToClose then
        for _, d in ipairs(dialogsToClose) do
            pcall(function() d.dismiss() end)
        end
    end
    pcall(stopLiveMode)
    if mainDlg then
        pcall(function() mainDlg.dismiss() end)
        mainDlg = nil
    end

    local ok, err = pcall(function()
        local shareIntent = Intent(Intent.ACTION_SEND)
        shareIntent.setType("text/plain")
        if subject then shareIntent.putExtra(Intent.EXTRA_SUBJECT, subject) end
        shareIntent.putExtra(Intent.EXTRA_TEXT, text)
        local chooser = Intent.createChooser(shareIntent, chooserTitle or "Share")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        ctx.startActivity(chooser)
    end)
    if not ok then
        logError("Share failed: " .. tostring(err))
        vibratePattern("error")
        notify("Could not open the share sheet: " .. tostring(err))
        pcall(reportError, "Share", tostring(err))
    end
    return ok
