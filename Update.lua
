-- کیمرہ پیرامیٹرز (چھوٹا پریویو، مسلسل فوکس) سیٹ کر کے منتخب کیمرہ کھولتا ہے
function openLiveCamera(holder)
    local id = liveModeState.cameraId or 0
    local cam = nil
    local ok = pcall(function() cam = Camera.open(id) end)
    if not ok or not cam then
        if id ~= 0 then
            liveModeState.cameraId = 0
            cam = Camera.open(0)
        else
            error("The camera could not be opened")
        end
    end
    liveModeState.camera = cam
    liveModeState.cameraRotation = nil

    -- فریم چھوٹے (≤640x480) رکھیں (کم ٹوکن خرچ ہوتے ہیں) تاکہ اپلوڈ اور جواب تیز ہو، اور
    -- مسلسل فوکس لگائیں تاکہ تصویر دھندلی نہ آئے
    pcall(function()
        local params = cam.getParameters()
        local sizes = params.getSupportedPreviewSizes()
        local bestW, bestH, bestArea = nil, nil, 0
        for i = 0, sizes.size() - 1 do
            local sz = sizes.get(i)
            local w, h = sz.width, sz.height
            if w <= 640 and h <= 480 and (w * h) > bestArea then
                bestW, bestH, bestArea = w, h, w * h
            end
        end
        if bestW then params.setPreviewSize(bestW, bestH) end
        pcall(function()
            local modes = params.getSupportedFocusModes()
            if modes and modes.contains("continuous-picture") then
                params.setFocusMode("continuous-picture")
            end
        end)
        cam.setParameters(params)
    end)

    pcall(function()
        local rot = getCameraRotation()
        local display = rot
        if liveModeState.cameraFront then display = (360 - rot) % 360 end
        cam.setDisplayOrientation(display)
    end)
    cam.setPreviewDisplay(holder)
    cam.startPreview()
    if liveModeState.torchOn then pcall(function() setLiveTorch(true) end) end
end

function setLiveTorch(on)
    local cam = liveModeState.camera
    if not cam then return false end
    return pcall(function()
        local params = cam.getParameters()
        params.setFlashMode(on and "torch" or "off")
        cam.setParameters(params)
    end)
end

function toggleLiveTorch(btn)
    local supported = false
    pcall(function()
        local modes = liveModeState.camera.getParameters().getSupportedFlashModes()
        supported = (modes ~= nil and modes.contains("torch"))
    end)
    if not supported then
        notify("This camera does not have a flashlight.")
        return
    end
    local want = not liveModeState.torchOn
    if setLiveTorch(want) then
        liveModeState.torchOn = want
        btn.setText(want and "🔦 Flash: ON" or "🔦 Flash: OFF")
        notify(want and "Flashlight on" or "Flashlight off")
    else
        notify("Could not change the flashlight.")
    end
end

function switchLiveCamera()
    if not (liveModeState.active and liveModeState.holder) then return end
    local count = 1
    pcall(function() count = tonumber(Camera.getNumberOfCameras()) or 1 end)
    if count < 2 then
        notify("This phone has only one camera.")
        return
    end
    local newId = 0
    if (liveModeState.cameraId or 0) == 0 then
        local frontId = nil
        pcall(function()
            for i = 0, count - 1 do
                local info = Camera.CameraInfo()
                Camera.getCameraInfo(i, info)
                if tonumber(info.facing) == 1 then
                    frontId = i
                    break
                end
            end
        end)
        if not frontId then
            notify("No front camera was found.")
            return
        end
        newId = frontId
    end
    liveModeState.busy = true
    pcall(function()
        liveModeState.camera.setPreviewCallback(nil)
        liveModeState.camera.stopPreview()
        liveModeState.camera.release()
    end)
    liveModeState.camera = nil
    liveModeState.cameraId = newId
    local ok, err = pcall(openLiveCamera, liveModeState.holder)
    liveModeState.busy = false
    if ok then
        notify(newId == 0 and "Back camera" or "Front camera")
    else
        pcall(reportError, "Switching camera", tostring(err))
    end
end

