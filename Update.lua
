-- کسی بھی جگہ سے: reportError("کہاں", "کیا ایرر", "اضافی تفصیل")
function reportError(source, message, details)
    local msg = tostring(message or "")
    pcall(function()
        logError("[" .. tostring(source) .. "] " .. msg .. ((details and details ~= "") and (" | " .. tostring(details)) or ""))
    end)
    -- ایک جیسا ایرر 20 سیکنڈ کے اندر بار بار ڈائیلاگ نہ دکھائے
    local key = tostring(source) .. "|" .. string.sub((msg:gsub("%d+", "#")), 1, 60)
    local now = os.time()
    if errorLastShown[key] and now - errorLastShown[key] < 20 then return end
    errorLastShown[key] = now
    local ok, report = pcall(buildErrorReport, source, msg, details)
    if not ok then report = "WHERE: " .. tostring(source) .. "\nERROR: " .. msg end
    table.insert(errorHistory, report)
    while #errorHistory > 30 do table.remove(errorHistory, 1) end
    pcall(vibratePattern, "error")
    pcall(showErrorDialog, report)
end

