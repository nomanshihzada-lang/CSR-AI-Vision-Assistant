function recordTokenUsage(usage)
    if not usage or type(usage) ~= "table" then return end
    -- Groq (OpenAI-سٹائل): prompt_tokens/completion_tokens/total_tokens
    -- (input_tokens/output_tokens بھی قبول کیے جاتے ہیں)
    local promptTokens = tonumber(usage.input_tokens) or tonumber(usage.prompt_tokens) or 0
    local responseTokens = tonumber(usage.output_tokens) or tonumber(usage.completion_tokens) or 0
    local totalTokens = tonumber(usage.total_tokens) or (promptTokens + responseTokens)

    -- پچھلے 60 سیکنڈ کا ٹوکن حساب (حد سے پہلے ہی رک جانے کے لیے)
    pcall(function()
        runtimeState.tokenWindow = runtimeState.tokenWindow or {}
        local now = os.time()
        table.insert(runtimeState.tokenWindow, { t = now, input = promptTokens, output = responseTokens })
        local keep = {}
        for _, e in ipairs(runtimeState.tokenWindow) do
            if now - e.t < 120 then table.insert(keep, e) end
        end
        runtimeState.tokenWindow = keep
    end)

    pcall(function()
        local today = getTodayDateString()
        local month = getCurrentMonthString()

        -- روزانہ کاؤنٹر (اگر تاریخ بدل گئی ہو تو ری سیٹ)
        local savedDay = aiPrefs.getString("tokens_day_date", "")
        local dayTotal = aiPrefs.getInt("tokens_day_total", 0)
        if savedDay ~= today then
            dayTotal = 0
        end
        dayTotal = dayTotal + totalTokens

        -- ماہانہ کاؤنٹر (اگر مہینہ بدل گیا ہو تو ری سیٹ)
        local savedMonth = aiPrefs.getString("tokens_month_str", "")
        local monthTotal = aiPrefs.getInt("tokens_month_total", 0)
        if savedMonth ~= month then
            monthTotal = 0
        end
        monthTotal = monthTotal + totalTokens

        -- ماہانہ بجٹ کی وارننگ: 80% اور 100% پر (ہر حد صرف ایک بار عبور ہونے پر)
        local prevMonthTotal = monthTotal - totalTokens
        local budgetLimit = getTokenBudgetMonthly()
        if budgetLimit and budgetLimit > 0 then
            if prevMonthTotal < budgetLimit and monthTotal >= budgetLimit then
                pcall(function() notify("Warning: your monthly token budget has been reached.") end)
            elseif prevMonthTotal < budgetLimit * 0.8 and monthTotal >= budgetLimit * 0.8 then
                pcall(function() notify("Warning: you have used 80 percent of your monthly token budget.") end)
            end
        end

        -- ہمیشہ کے لیے کل کاؤنٹر (کبھی ری سیٹ نہیں ہوتا)
        local allTimeTotal = aiPrefs.getInt("tokens_alltime_total", 0) + totalTokens
        local allTimeCalls = aiPrefs.getInt("tokens_alltime_calls", 0) + 1

        aiEditor.putString("tokens_day_date", today)
        aiEditor.putInt("tokens_day_total", dayTotal)
        aiEditor.putString("tokens_month_str", month)
        aiEditor.putInt("tokens_month_total", monthTotal)
        aiEditor.putInt("tokens_alltime_total", allTimeTotal)
        aiEditor.putInt("tokens_alltime_calls", allTimeCalls)
        aiEditor.commit()
    end)

    logInfo("Token usage: prompt=" .. promptTokens .. " response=" .. responseTokens .. " total=" .. totalTokens)
end

