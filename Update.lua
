        return uriToBase64(selectedPhotoUri)
    elseif selectedPhotoPath and selectedPhotoPath ~= "" then
        return pathToBase64(selectedPhotoPath)
    end
    return nil
end

-- Offline OCR کے لیے موجودہ منتخب امیج کا Bitmap حاصل کریں
function decodeSelectedBitmap()
    local ok, bmp = pcall(function()
        if selectedPhotoUri then
            local resolver = ctx.getContentResolver()
            local inputStream = resolver.openInputStream(selectedPhotoUri)
            if not inputStream then return nil end
            local b = BitmapFactory.decodeStream(inputStream)
            pcall(function() inputStream.close() end)
            return b
        elseif selectedPhotoPath and selectedPhotoPath ~= "" then
            return BitmapFactory.decodeFile(selectedPhotoPath)
        end
        return nil
    end)
    if ok then return bmp end
    logError("decodeSelectedBitmap failed: " .. tostring(bmp))
    return nil
end

-- Safe Mode: لگاتار ناکامیوں کے بعد فیچر کو عارضی بند کرنا تاکہ ایپ کریش نہ ہو
-- اور یوزر کو واضح پیغام ملے۔ کامیاب کال پر کاؤنٹر خودکار ری سیٹ ہو جاتا ہے۔
function enterSafeModeIfNeeded()
    runtimeState.consecutiveFailures = runtimeState.consecutiveFailures + 1
    logWarn("Consecutive failure count: " .. runtimeState.consecutiveFailures)
    if runtimeState.consecutiveFailures >= CONFIG.SAFE_MODE_FAILURE_THRESHOLD and not runtimeState.safeModeActive then
        runtimeState.safeModeActive = true
        runtimeState.safeModeSince = os.time()
        logError("SAFE MODE ACTIVATED after " .. runtimeState.consecutiveFailures .. " consecutive failures.")
        notify("Safe Mode فعال: بار بار ایرر آنے کی وجہ سے AI فیچر عارضی طور پر روکا گیا۔ Settings چیک کریں۔")
    end
end

function resetFailureState()
    if runtimeState.consecutiveFailures > 0 or runtimeState.safeModeActive then
        logInfo("API call succeeded — resetting failure counter / leaving Safe Mode.")
    end
    runtimeState.consecutiveFailures = 0
    runtimeState.safeModeActive = false
end

-- اندرونی: ایک ہی کوشش (attempt) کے لیے HTTP کال
-- Groq کے ایرر جواب سے پڑھنے کے قابل پیغام نکالتا ہے
-- (فارمیٹ: {"error":{"message":"...","type":"..."}})
local function extractAIErrorMessage(data)
    if not data or data == "" then return nil end
    local ok, decoded = pcall(cjson.decode, data)
    if ok and type(decoded) == "table" then
        local e = decoded.error
        if type(e) == "string" then return e end
        if type(e) == "table" and e.message then return tostring(e.message) end
        if type(decoded.message) == "string" then return decoded.message end
    end
    return nil
end

-- Chat Completions کے جواب سے متن نکالتا ہے (choices[1].message.content)
-- ماڈل کی سوچ والے حصے (<think>...</think>) اگر آ جائیں تو ہٹا دیے جاتے ہیں
local function extractAIText(decoded)
    if type(decoded.choices) == "table" and decoded.choices[1] and type(decoded.choices[1].message) == "table" then
        local m = decoded.choices[1].message.content
        if type(m) == "string" then
            m = m:gsub("<think>.-</think>", "")
            m = m:gsub("^%s+", ""):gsub("%s+$", "")
            if m ~= "" then return m end
        end
    end
    return nil
end

-- Groq کے 429 پیغام ("Please try again in 7m12.3s") سے انتظار کا وقت (سیکنڈ) نکالتا ہے
local function parseRetryAfterSeconds(msg)
    if not msg then return nil end
    local s = string.lower(tostring(msg))
    local tail = s:match("try again in%s+([%w%.%s]+)")
    if not tail then return nil end
    local t = tail:sub(1, 24)
    local total, found = 0, false
    local ms = t:match("([%d%.]+)ms")
    if ms then
        t = t:gsub("[%d%.]+ms", "")
        total = total + (tonumber(ms) or 0) / 1000
        found = true
    end
    local h = t:match("(%d+)h")
    if h then total = total + tonumber(h) * 3600; found = true end
    local m = t:match("(%d+)m")
    if m then total = total + tonumber(m) * 60; found = true end
    local sec = t:match("([%d%.]+)s")
    if sec then total = total + (tonumber(sec) or 0); found = true end
    if found then return math.ceil(total) end
    return nil
end

local function formatDuration(sec)
    sec = tonumber(sec) or 0
    if sec < 90 then return math.max(1, math.floor(sec)) .. " seconds" end
    if sec < 5400 then return math.ceil(sec / 60) .. " minutes" end
    return string.format("%.1f", sec / 3600) .. " hours"
end

-- Groq کے 429 پیغام سے اس اکاؤنٹ کی اصل حدیں سیکھتا ہے، مثلاً
-- "on input tokens per minute (ITPM): Limit 7000" یا "(OTPM): Limit 1000"
local function learnLimitsFromMessage(msg)
    if not msg then return end
    runtimeState.limits = runtimeState.limits or {}
    for name, value in tostring(msg):gmatch("%((%u+)%):%s*Limit%s+(%d+)") do
        runtimeState.limits[name] = tonumber(value)
    end
end

-- کتنے سیکنڈ بعد اتنے ٹوکن حد پار کیے بغیر بھیجے جا سکتے ہیں (0 = ابھی)۔ یہ تب ہی
-- کام کرتا ہے جب Groq کوئی حد بتا چکا ہو (اپ گریڈ شدہ پلان پر بلاوجہ انتظار نہیں)
function secondsUntilBudget(estInput, estOutput)
    local limits = runtimeState.limits
    if not limits then return 0 end
    local win = runtimeState.tokenWindow or {}
    local now = os.time()
    local function needed(limit, key, est)
        if not limit then return 0 end
        limit = limit * 0.9
        local entries = {}
        for _, e in ipairs(win) do
            if now - e.t < 60 then table.insert(entries, e) end
        end
        table.sort(entries, function(a, b) return a.t < b.t end)
        local total = est
        for _, e in ipairs(entries) do total = total + (e[key] or 0) end
        if total <= limit then return 0 end
        local wait = 0
        for _, e in ipairs(entries) do
            total = total - (e[key] or 0)
            wait = (e.t + 60) - now
            if total <= limit then break end
        end
        return math.max(0, wait + 1)
    end
    local w1 = needed(limits.ITPM or limits.TPM, "input", estInput or 0)
    local w2 = needed(limits.OTPM, "output", estOutput or 0)
    return math.max(w1, w2)
end

-- ایک ہی کوشش (attempt) کے لیے Groq کو HTTP کال
-- onDone(text, errorMessage, retryable, httpStatus, retryAfterSeconds, kind, extra)
local function attemptAICall(apiKey, payload, attemptNumber, model, onDone)
    local headers = {
        ["Content-Type"] = "application/json",
        ["Authorization"] = "Bearer " .. tostring(apiKey)
    }
    local ok, err = pcall(function()
        Http.post(AI_API_URL, cjson.encode(payload), headers, guard("http callback (line 1205)", function(status, data)
            status = tonumber(status) or 0
            if status == 200 then
                local decodeOk, decoded = pcall(cjson.decode, data)
                if decodeOk and type(decoded) == "table" then
                    local text = extractAIText(decoded)
                    if text then
                        pcall(function() recordTokenUsage(decoded.usage) end)
                        onDone(text, nil, false, 200)
                    else
                        local finish = nil
                        pcall(function() finish = decoded.choices[1].finish_reason end)
                        if finish == "length" then
                            onDone(nil, "جواب نامکمل رہا (ماڈل نے حد پار کر لی)۔ دوبارہ کوشش کریں۔", true, 200)
                        else
                            onDone(nil, "AI نے کوئی متن واپس نہیں کیا (ہو سکتا ہے سیفٹی فلٹر نے روک دیا ہو)۔", false, 200)
                        end
                    end
                else
                    onDone(nil, "AI کا جواب درست فارمیٹ میں نہیں آیا۔", true, 200)
                end
            elseif status == 400 then
                local msg = extractAIErrorMessage(data)
                onDone(nil, "Error 400 (درخواست درست نہیں): " .. tostring(msg or "تفصیل دستیاب نہیں"), false, 400)
            elseif status == 401 or status == 403 then
                local msg = extractAIErrorMessage(data)
                onDone(nil, "Error " .. status .. ": API Key غلط ہے یا اجازت نہیں۔ Settings میں Groq key (gsk_ سے شروع ہونے والی) چیک کریں۔ " .. tostring(msg or ""), false, status)
            elseif status == 404 then
                onDone(nil, "Error 404: منتخب ماڈل (" .. model .. ") دستیاب نہیں۔ Settings میں کوئی اور ماڈل منتخب کریں۔", false, 404)
            elseif status == 413 then
                onDone(nil, "Error 413: تصویر/درخواست بہت بڑی ہے۔", false, 413)
            elseif status == 408 or status == 429 then
                local msg = extractAIErrorMessage(data)
                local wait = parseRetryAfterSeconds(msg)
                local lower = string.lower(tostring(msg or ""))
                learnLimitsFromMessage(msg)
                -- "Request too large": مانگے گئے آؤٹ پٹ ٹوکن حد سے زیادہ ہیں؛ انتظار نہیں، سائز کم کر کے فوراً دوبارہ
                if status == 429 and string.find(lower, "request too large", 1, true) then
                    local limit = tonumber(string.match(tostring(msg), "Limit%s+(%d+)"))
                    if string.find(lower, "output tokens", 1, true) and limit then
                        onDone(nil, "The answer size was too big for Groq's free per-minute output limit (" .. limit .. " tokens). Shrinking it and trying again.", false, status, nil, "reduce_output", math.max(100, math.floor(limit * 0.6)))
                    else
                        onDone(nil, "This request is bigger than Groq's free per-minute limit allows (" .. tostring(string.match(tostring(msg), "%(([%u]+)%)") or "tokens") .. "). Try again with a smaller image or less text.", false, status)
                    end
                    return
                end
                local daily = string.find(lower, "per day", 1, true) or string.find(lower, "(tpd)", 1, true) or string.find(lower, "(rpd)", 1, true)
                local friendly
                if status == 408 then
                    friendly = "The request timed out. Trying again."
                elseif daily then
                    friendly = "Groq's free DAILY limit has been reached" .. (wait and (". It resets in about " .. formatDuration(wait)) or "") .. ". To keep using the AI, wait for the reset or upgrade to the Groq Developer plan."
                else
                    friendly = "Groq's free per-minute limit was reached" .. (wait and (". Waiting about " .. formatDuration(wait) .. " before trying again") or "") .. "."
                end
                onDone(nil, friendly, true, status, wait)
            elseif status >= 500 then
                onDone(nil, "Server Error " .. status .. ": Groq سروس عارضی طور پر دستیاب نہیں۔", true, status)
            elseif status == 0 or status < 0 then
                onDone(nil, "انٹرنیٹ/نیٹ ورک کا مسئلہ — سرور تک رسائی نہیں ہوئی۔", true, 0)
            else
                local msg = extractAIErrorMessage(data)
                onDone(nil, "API Error " .. status .. ": " .. tostring(msg or ""), false, status)
            end
        end))
    end)
    if not ok then
        logError("attemptAICall pcall failed: " .. tostring(err))
        onDone(nil, "Network/Runtime error while calling API: " .. tostring(err), true, 0)
    end
end

-- =====================================================================
-- RESPONSE CACHE — اگر بالکل وہی تصویر، وہی موڈ اور وہی ماڈل دوبارہ
-- پروسیس کی جائے (مثلاً Batch میں غلطی سے دو بار، یا دوبارہ تصویر
-- منتخب کرنے پر)، تو نیا API کال کرنے کے بجائے محفوظ شدہ جواب فوراً
-- واپس کر دیا جاتا ہے — وقت اور Tokens دونوں بچتے ہیں۔
-- =====================================================================
local RESPONSE_CACHE_FILE_NAME = "CSR_AI_Assistant_Cache.json"
local RESPONSE_CACHE_MAX_ENTRIES = 30

function simpleHash(str)
    if not str then return "0_0" end
    local hash = 5381
    local len = #str
    local step = math.max(1, math.floor(len / 2000))
    for i = 1, len, step do
        hash = (hash * 33 + string.byte(str, i)) % 2147483647
    end
    return tostring(hash) .. "_" .. tostring(len)
end

function getResponseCacheFilePath()
    return (os.getenv("EXTERNAL_STORAGE") or "/sdcard") .. "/" .. RESPONSE_CACHE_FILE_NAME
end

function loadResponseCache()
    local ok, result = pcall(function()
        local f = io.open(getResponseCacheFilePath(), "r")
        if not f then return {} end
        local content = f:read("*a")
        f:close()
        if not content or content == "" then return {} end
        local decodeOk, decoded = pcall(cjson.decode, content)
        if decodeOk and type(decoded) == "table" then return decoded end
        return {}
    end)
    if ok then return result end
    return {}
end

function getCachedResponse(key)
    local ok, cache = pcall(loadResponseCache)
    if ok and cache and cache[key] then return cache[key].text end
    return nil
end

function setCachedResponse(key, text)
    if not isSaveHistoryEnabled() then return end   -- پرائیویسی ٹوگل بند ہو تو کیش بھی محفوظ نہیں ہوتا
    pcall(function()
        local cache = loadResponseCache()
        cache[key] = { text = text, time = os.time() }
        local count = 0
        for _ in pairs(cache) do count = count + 1 end
        if count > RESPONSE_CACHE_MAX_ENTRIES then
            local entries = {}
            for k, v in pairs(cache) do table.insert(entries, {k = k, time = v.time or 0}) end
            table.sort(entries, function(a, b) return a.time < b.time end)
            local toRemove = count - RESPONSE_CACHE_MAX_ENTRIES
            for i = 1, toRemove do cache[entries[i].k] = nil end
        end
        local f = io.open(getResponseCacheFilePath(), "w")
        if f then
            f:write(cjson.encode(cache))
            f:close()
        end
    end)
end

-- عوامی فنکشن: خودکار ری-ٹرائی اور Safe Mode کے ساتھ Groq کو امیج بھیجنا
-- opts.maxTokens: جواب کی زیادہ سے زیادہ لمبائی (Live Mode میں چھوٹی رکھی جاتی ہے)
function callAIWithImage(apiKey, model, base64Data, prompt, callback, opts)
    opts = opts or {}
    local maxTokens = opts.maxTokens or 700
    local requestedModel = model

    -- اگر حال ہی میں اس ماڈل سے دوسرے ماڈل پر منتقلی ہوئی تھی (5 منٹ تک) تو وہی استعمال کریں
    local override = runtimeState.modelOverride
    if override and override.from == model and os.time() < override.expires and aiApiDetails[override.model] then
        model = override.model
    end
    local triedModels = {}
    triedModels[model] = true
    local switchedModel = false

    if runtimeState.safeModeActive then
        -- Safe Mode خود بخود 60 سیکنڈ بعد ختم ہو جاتا ہے (پہلے یہ ہمیشہ کے لیے بلاک کر دیتا تھا)
        if os.time() - (runtimeState.safeModeSince or 0) >= 60 then
            runtimeState.safeModeActive = false
            runtimeState.consecutiveFailures = 0
            logInfo("Safe Mode expired automatically after 60 seconds.")
        else
            logWarn("callAIWithImage blocked: Safe Mode is active.")
            callback(nil, "Safe Mode فعال ہے۔ بار بار ایرر کی وجہ سے AI عارضی طور پر (تقریباً ایک منٹ کے لیے) بند ہے۔ تھوڑی دیر بعد دوبارہ کوشش کریں۔")
            return
        end
    end

    -- Live Mode/Voice Q&A میں ہر فریم نیا ہوتا ہے، اس لیے کیش (فائل پڑھنا/لکھنا) صرف وقت ضائع کرتا ہے
    local cacheKey = nil
    if not opts.noCache and base64Data then
        cacheKey = simpleHash(base64Data .. "|" .. model .. "|" .. prompt)
        local cachedText = getCachedResponse(cacheKey)
        if cachedText then
            logInfo("Response cache hit — skipping API call.")
            callback(cachedText, nil)
            return
        end
    end

    local modelInfo = aiApiDetails[model]
    if not modelInfo then
        logError("callAIWithImage: invalid model '" .. tostring(model) .. "'")
        callback(nil, "غلط ماڈل منتخب ہے — Settings میں کوئی Qwen ماڈل منتخب کریں۔")
        return
    end

    -- base64Data نہ ہو تو صرف متن بھیجا جاتا ہے (Voice Q&A میں فریم نہ ملے تب بھی جواب ملے)
    local contentParts = { { type = "text", text = prompt } }
    if base64Data then
        table.insert(contentParts, { type = "image_url", image_url = { url = "data:image/jpeg;base64," .. base64Data } })
    end
    -- صرف متن والی درخواست میں content سادہ سٹرنگ ہو (سرور یہی فارمیٹ سب سے محفوظ مانتا ہے)
    local contentField = contentParts
    if not base64Data then contentField = prompt end
    if runtimeState.maxOutputCap and maxTokens > runtimeState.maxOutputCap then
        maxTokens = runtimeState.maxOutputCap
    end
    local payload = {
        model = modelInfo.id,
        messages = {{
            role = "user",
            content = contentField
        }},
        max_completion_tokens = maxTokens,
        stream = false
    }
    -- سوچنے (reasoning) کو بند رکھنے سے جواب بہت تیز آتا ہے (Live Mode کے لیے ضروری)
    if CONFIG.REASONING_EFFORT and CONFIG.REASONING_EFFORT ~= "" then
        payload.reasoning_effort = CONFIG.REASONING_EFFORT
    end

    logInfo("Calling Groq model=" .. modelInfo.id)

    local function tryAttempt(attemptNumber)
        attemptAICall(apiKey, payload, attemptNumber, model, function(result, errMsg, retryable, httpStatus, retryAfter, kind, extra)
            if result then
                logInfo("Groq call succeeded on attempt " .. attemptNumber)
                resetFailureState()
                if switchedModel then
                    runtimeState.modelOverride = { from = requestedModel, model = model, expires = os.time() + 300 }
                end
                if cacheKey then setCachedResponse(cacheKey, result) end
                callback(result, nil)
                return
            end

            logError("Groq call failed (attempt " .. attemptNumber .. "): " .. tostring(errMsg))

            -- اگر ماڈل reasoning_effort کی قدر قبول نہ کرے (400) تو اسے ہٹا کر
            -- فوراً ایک بار دوبارہ کوشش کریں (صارف کو ایرر دکھائے بغیر)
            if httpStatus == 400 and payload.reasoning_effort and string.find(string.lower(tostring(errMsg)), "reasoning", 1, true) then
                logWarn("Model rejected reasoning_effort — retrying without it.")
                payload.reasoning_effort = nil
                tryAttempt(attemptNumber)
                return
            end

            -- آؤٹ پٹ حد سے بڑا مطالبہ: سائز کم کر کے (اور آئندہ کے لیے یاد رکھ کر) ایک بار فوراً دوبارہ
            if kind == "reduce_output" and extra and payload.max_completion_tokens and payload.max_completion_tokens > extra and not payload.__reduced then
                logWarn("Reducing max_completion_tokens from " .. tostring(payload.max_completion_tokens) .. " to " .. tostring(extra))
                runtimeState.maxOutputCap = extra
                payload.max_completion_tokens = extra
                payload.__reduced = true
                tryAttempt(attemptNumber)
                return
            end

            -- 429 پر Groq کے بتائے ہوئے وقت تک انتظار؛ اگر انتظار 20 سیکنڈ سے لمبا ہو
            -- (مثلاً روزانہ حد) تو بار بار کوشش کرنے کے بجائے فوراً واضح پیغام واپس کریں
            local longWait = (httpStatus == 429 and retryAfter and retryAfter > 20)
            if retryable and not longWait and attemptNumber <= CONFIG.MAX_RETRIES then
                local delayMs = CONFIG.RETRY_DELAY_MS
                if httpStatus == 429 and retryAfter then
                    delayMs = math.max(delayMs, math.floor(retryAfter * 1000) + 300)
                end
                local handler = Handler(Looper.getMainLooper())
                handler.postDelayed(Runnable({ run = guard("run (line 1438)", function()
                    tryAttempt(attemptNumber + 1)
                end) }), delayMs)
            else
                -- ماڈل دستیاب نہیں (404) یا rate limit (429) ہو تو دوسرے Qwen ماڈل پر خودکار منتقلی
                if httpStatus == 404 or httpStatus == 429 then
                    local altName = nil
                    for _, name in ipairs(AI_MODELS) do
                        if not triedModels[name] and aiApiDetails[name] then
                            altName = name
                            break
                        end
                    end
                    if altName then
                        triedModels[altName] = true
                        logWarn("Switching model from " .. tostring(model) .. " to " .. altName .. " (status " .. tostring(httpStatus) .. ")")
                        model = altName
                        switchedModel = true
                        payload.model = aiApiDetails[altName].id
                        pcall(function() notify("Switching to " .. altName .. " because the first model is unavailable or busy.") end)
                        tryAttempt(1)
                        return
                    end
                end
                -- صرف سرور/نیٹ ورک کی خرابیاں Safe Mode کی طرف گنی جاتی ہیں؛
                -- غلط key/ماڈل جیسی ترتیب کی غلطیاں نہیں
                -- rate limit (429) کو Safe Mode کی طرف نہیں گنا جاتا
                if retryable and httpStatus ~= 429 then enterSafeModeIfNeeded() end
                if not opts.silentErrors then
                    pcall(reportError, "AI request (" .. tostring(model) .. ")", tostring(errMsg), "HTTP status: " .. tostring(httpStatus))
                end
                callback(nil, errMsg, httpStatus, retryAfter)
            end
        end)
    end

    -- حد کے قریب ہوں تو ناکام ہونے کے بجائے مناسب وقت انتظار کر کے بھیجیں (لائیو فریم اپنا
    -- انتظار خود شیڈیولر میں کرتے ہیں)
    local estInput = (base64Data and 2400 or 0) + math.floor(#prompt / 3)
    local wait = 0
    if not opts.live then wait = secondsUntilBudget(estInput, maxTokens) end
    if wait > 0 and wait <= 70 then
        pcall(notify, "Waiting about " .. formatDuration(wait) .. " to stay inside Groq's free limit...")
        local waitHandler = Handler(Looper.getMainLooper())
        waitHandler.postDelayed(Runnable({ run = function() tryAttempt(1) end }), math.floor(wait * 1000))
    else
        tryAttempt(1)
    end
end

