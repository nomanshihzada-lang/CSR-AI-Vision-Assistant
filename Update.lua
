local historyFilePath = nil
pcall(function()
    historyFilePath = (os.getenv("EXTERNAL_STORAGE") or "/sdcard") .. "/CSR_AI_Assistant_History.json"
end)

function loadHistory()
    if not historyFilePath then return {} end
    local ok, list = pcall(function()
        local f = io.open(historyFilePath, "r")
        if not f then return {} end
        local content = f:read("*a")
        f:close()
        if not content or content == "" then return {} end
        local decodeOk, decoded = pcall(cjson.decode, content)
        if decodeOk and type(decoded) == "table" then return decoded end
        return {}
    end)
    if ok then return list end
    return {}
end

function saveHistoryEntry(mode, resultText)
    if not historyFilePath or not resultText or resultText == "" then return end
    pcall(function()
        local history = loadHistory()
        table.insert(history, 1, {
            time = os.date("%Y-%m-%d %H:%M:%S"),
            mode = mode,
            text = resultText
        })
        while #history > CONFIG.HISTORY_MAX_ITEMS do
            table.remove(history)
        end
        local f = io.open(historyFilePath, "w")
        if f then
            f:write(cjson.encode(history))
            f:close()
        end
        logInfo("History entry saved: " .. tostring(mode))
    end)
end

function clearHistory()
    if not historyFilePath then return end
    pcall(function()
        local f = io.open(historyFilePath, "w")
        if f then f:write("[]"); f:close() end
    end)
    logInfo("History cleared by user.")
end

function exportHistoryAsText()
    local history = loadHistory()
    if #history == 0 then return nil end
    local lines = {}
    for _, item in ipairs(history) do
        table.insert(lines, "[" .. item.time .. "] " .. item.mode .. "\n" .. item.text .. "\n")
    end
    return table.concat(lines, "\n---------------------------\n\n")
end

function shareHistory()
    local text = exportHistoryAsText()
    if not text then
        notify("کوئی محفوظ شدہ نتیجہ نہیں ہے")
        return
    end
    if #text > 30000 then
        text = "...(truncated, showing most recent)...\n\n" .. text:sub(1, 30000)
    end
    local ok, err = pcall(function()
        local shareIntent = Intent(Intent.ACTION_SEND)
        shareIntent.setType("text/plain")
        shareIntent.putExtra(Intent.EXTRA_SUBJECT, "CSR AI Assistant — History Export")
        shareIntent.putExtra(Intent.EXTRA_TEXT, text)
        local chooser = Intent.createChooser(shareIntent, "Share History")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        ctx.startActivity(chooser)
    end)
    if not ok then
        logError("shareHistory failed: " .. tostring(err))
        vibratePattern("error")
        notify("Share نہیں ہو سکا: " .. tostring(err))
    end
end

