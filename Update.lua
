-- لمبے متن کو حصوں (Parts) میں بانٹتا ہے؛ پیراگراف کے بیچ سے نہیں (اور UTF-8 حرف کے بیچ سے کبھی نہیں)
function splitIntoParts(text, maxBytes)
    text = tostring(text or "")
    if #text <= maxBytes then return { text } end
    local parts, current = {}, ""
    for para in (text .. "\n"):gmatch("(.-)\n") do
        while #para > maxBytes do
            local piece = safeUtf8Cut(para, maxBytes)
            if #piece == 0 then break end
            if #current > 0 then
                table.insert(parts, current)
                current = ""
            end
            table.insert(parts, piece)
            para = para:sub(#piece + 1)
        end
        if #current > 0 and #current + #para + 1 > maxBytes then
            table.insert(parts, current)
            current = para
        elseif #current > 0 then
            current = current .. "\n" .. para
        else
            current = para
        end
    end
    if #current > 0 then table.insert(parts, current) end
    if #parts == 0 then parts = { text } end
    return parts
end

