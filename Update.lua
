function analyzeCurrentScreen()
    local root = nil
    pcall(function() root = service.getRootInActiveWindow() end)
    if not root then
        return "Cannot access current screen. Make sure accessibility service is enabled."
    end
    
    local elements = {}
    local function collectVisibleNodes(node, depth)
        if depth > 8 then return end
        local isVisible = false
        pcall(function() isVisible = node.isVisibleToUser() end)
        if isVisible then
            local text = ""
            pcall(function() 
                local t = node.getText()
                if t then text = tostring(t) end
            end)
            local desc = ""
            pcall(function() 
                local d = node.getContentDescription()
                if d then desc = tostring(d) end
            end)
            if text ~= "" or desc ~= "" then
                table.insert(elements, {text = text, desc = desc})
            end
        end
        local childCount = 0
        pcall(function() childCount = node.getChildCount() end)
        for i = 0, childCount - 1 do
            local child = nil
            pcall(function() child = node.getChild(i) end)
            if child then collectVisibleNodes(child, depth + 1) end
        end
    end
    collectVisibleNodes(root, 0)
    
    if #elements == 0 then
        return "No text elements found on current screen."
    end
    
    local summary = "📱 **Current Screen Summary**\n\nFound " .. #elements .. " visible text elements.\n\n"
    for i = 1, math.min(20, #elements) do
        summary = summary .. "- " .. (elements[i].text ~= "" and elements[i].text or elements[i].desc) .. "\n"
    end
    if #elements > 20 then summary = summary .. "... and " .. (#elements - 20) .. " more." end
    return summary
end

function pathToBase64(imagePath)
    if not imagePath or imagePath == "" then return nil end
    local imgFile = File_CLASS(imagePath)
    if not imgFile.exists() or not imgFile.canRead() then return nil end
    
    local options = BitmapFactory.Options()
    options.inJustDecodeBounds = true
    BitmapFactory.decodeFile(imagePath, options)
    
    local maxDimension = CONFIG.MAX_IMAGE_DIMENSION
    local scale = 1
    if options.outHeight > maxDimension or options.outWidth > maxDimension then
        scale = math.max(math.floor(options.outHeight / maxDimension), math.floor(options.outWidth / maxDimension))
    end
    options.inSampleSize = scale
    options.inJustDecodeBounds = false
    options.inPreferredConfig = Bitmap.Config.RGB_565
    
    local bitmap = BitmapFactory.decodeFile(imagePath, options)
    if not bitmap then
        logError("pathToBase64: BitmapFactory.decodeFile returned nil for " .. tostring(imagePath))
        return nil
    end
    
    local width = bitmap.getWidth()
    local height = bitmap.getHeight()
    if width > maxDimension or height > maxDimension then
        local newWidth, newHeight = width, height
        if width > height then
            newWidth = maxDimension
            newHeight = (height * maxDimension / width)
        else
            newHeight = maxDimension
            newWidth = (width * maxDimension / height)
        end
        -- پرانا bitmap فوری طور پر ریسائیکل کریں تاکہ میموری فارغ ہو (کوئی لیک نہ رہے)
        local scaled = Bitmap.createScaledBitmap(bitmap, newWidth, newHeight, true)
        bitmap.recycle()
        bitmap = scaled
    end
    
    local outputStream = ByteArrayOutputStream()
    bitmap.compress(Bitmap.CompressFormat.JPEG, CONFIG.JPEG_QUALITY, outputStream)
    local imageBytes = outputStream.toByteArray()
    outputStream.close()
    bitmap.recycle()
    collectgarbage("collect")
    logInfo("pathToBase64: image encoded, size=" .. tostring(#imageBytes) .. " bytes")
    return Base64.encodeToString(imageBytes, Base64.NO_WRAP)
end

-- =====================================================================
-- کیمرہ کیپچر — دوبارہ ڈیزائن شدہ (Content URI کا طریقہ)
--
-- پرانا مسئلہ: Uri.fromFile() سے بننے والا "file://" URI کیمرہ ایپ کو
-- بھیجا جاتا تھا۔ Android 7 (API 24) سے، ایسا کوئی بھی URI جو آپ کی ایپ
-- سے باہر (دوسری ایپ کو) بھیجا جائے، FileUriExposedException دیتا ہے —
-- یہ ایک fatal/uncaught exception ہے جو پورے پراسیس کو کریش کر سکتا ہے،
-- اور چونکہ یہ ایک Accessibility Service کے اندر ہو رہا تھا، بار بار
-- کریش ہونے سے سسٹم اَنسٹیبل ہو کر ڈیوائس ری اسٹارٹ جیسا برتاؤ دکھا سکتا
-- ہے۔ اوپر موجود StrictMode کوڈ اسے حل نہیں کرتا کیونکہ یہ چیک
-- StrictMode کی پالیسی سے آزاد، فریم ورک میں خود بخود لاگو ہوتا ہے۔
--
-- نیا/محفوظ طریقہ: ContentResolver.insert() کے ذریعے براہِ راست
-- MediaStore میں ایک نئی خالی entry بنائی جاتی ہے، جو ایک اصلی
-- "content://" URI دیتی ہے — یہ کبھی FileUriExposedException نہیں دیتا
-- اور کسی FileProvider/Manifest تبدیلی کی ضرورت نہیں پڑتی۔
-- =====================================================================
function createCameraOutputUri()
    local ok, result = pcall(function()
        local values = ContentValues()
        values.put(MediaStore.Images.Media.DISPLAY_NAME, "CSR_AI_" .. os.time() .. ".jpg")
        values.put(MediaStore.Images.Media.MIME_TYPE, "image/jpeg")
        local resolver = ctx.getContentResolver()
        return resolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, values)
    end)
    if ok and result then
        logInfo("createCameraOutputUri: created new MediaStore entry")
        return result
    end
    logError("createCameraOutputUri failed: " .. tostring(result))
    return nil
end

-- content:// URI سے براہِ راست بیس 64 حاصل کریں (کیمرے سے آنے والی تصویر کے لیے)
function uriToBase64(uri)
    local ok, result = pcall(function()
        local resolver = ctx.getContentResolver()
        local inputStream = resolver.openInputStream(uri)
        if not inputStream then return nil end

        local options = BitmapFactory.Options()
        options.inPreferredConfig = Bitmap.Config.RGB_565
        local bitmap = BitmapFactory.decodeStream(inputStream, nil, options)
        pcall(function() inputStream.close() end)
        if not bitmap then return nil end

        local maxDimension = CONFIG.MAX_IMAGE_DIMENSION
        local width = bitmap.getWidth()
        local height = bitmap.getHeight()
        if width > maxDimension or height > maxDimension then
            local newWidth, newHeight = width, height
            if width > height then
                newWidth = maxDimension
                newHeight = (height * maxDimension / width)
            else
                newHeight = maxDimension
                newWidth = (width * maxDimension / height)
            end
            local scaled = Bitmap.createScaledBitmap(bitmap, newWidth, newHeight, true)
            bitmap.recycle()
            bitmap = scaled
        end

        local outputStream = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.JPEG, CONFIG.JPEG_QUALITY, outputStream)
        local imageBytes = outputStream.toByteArray()
        outputStream.close()
        bitmap.recycle()
        collectgarbage("collect")
        return Base64.encodeToString(imageBytes, Base64.NO_WRAP)
    end)
    if ok and result then
        logInfo("uriToBase64: image encoded from content URI")
        return result
    end
    logError("uriToBase64 failed: " .. tostring(result))
    return nil
end

