    local listDlg = LuaDialog(ctx)
    listDlg.setTitle("منتخب کریں (متعدد تصاویر، آخری 100)")
    listDlg.setView(listLayout)
    listDlg.setPositiveButton("Process Selected", function()
        local selectedPaths = {}
        local ok, err = pcall(function()
            local checkedPositions = listView.getCheckedItemPositions()
            for i = 0, #filePaths - 1 do
                local isChecked = checkedPositions.get(i)
                if isChecked then
                    table.insert(selectedPaths, filePaths[i + 1])
                end
            end
        end)
        if not ok then
            logError("Batch selection read failed: " .. tostring(err))
            notify("انتخاب پڑھنے میں مسئلہ ہوا")
            return
        end
        if #selectedPaths == 0 then
            notify("کوئی تصویر منتخب نہیں کی گئی")
            return
        end
        callback(selectedPaths)
    end)
    listDlg.setNegativeButton("Cancel", nil)
    listDlg.show()
end

function processBatchImages(paths)
    local apiKey = getAIApiKey()
    if not apiKey or apiKey == "" then
        vibratePattern("error")
        notify("API Key missing! Set in Settings")
        return
    end
    if not isNetworkAvailable() then
        vibratePattern("error")
        notify("انٹرنیٹ کنکشن نہیں ہے۔ Batch Processing کے لیے انٹرنیٹ ضروری ہے۔")
        return
    end

    local selectedOption = getSelectedRecognizeOption()
    local lang = getSelectedLanguage()
    local total = #paths
    local results = {}
    local index = 1

    showProgress("Batch Processing 1/" .. total .. "...")
    logInfo("Batch processing started: " .. total .. " images, mode=" .. selectedOption)

    local function finishBatch()
        hideProgress()
        local reportLines = {}
        for i, r in ipairs(results) do
            table.insert(reportLines, "[" .. i .. "] " .. r.name .. "\n" .. r.text .. "\n")
        end
        local combined = table.concat(reportLines, "\n---------------------------\n\n")
        showResultDialog("Batch Results (" .. total .. " images — " .. selectedOption .. ")", combined)
        saveHistoryEntry("Batch (" .. selectedOption .. ", " .. total .. " images)", combined)
        vibratePattern("success")
        logInfo("Batch processing finished: " .. total .. " images")
    end

    local function processNext()
        if index > total then
            finishBatch()
            return
        end

        local path = paths[index]
        local name = "image_" .. index
        pcall(function() name = File_CLASS(path).getName() end)
        showProgress("Batch Processing " .. index .. "/" .. total .. " — " .. name)

        local base64Data = pathToBase64(path)
        if not base64Data then
            logError("Batch: failed to read image " .. tostring(path))
            table.insert(results, {name = name, text = "(تصویر پڑھی نہیں جا سکی)"})
            index = index + 1
            processNext()
            return
        end

        local prompt = buildPromptForMode(selectedOption, lang)
        callAIWithImage(apiKey, getAIModel(), base64Data, prompt, function(res, err)
            table.insert(results, {name = name, text = res or ("خرابی: " .. tostring(err))})
            index = index + 1
            processNext()
        end)
    end

    processNext()
end

