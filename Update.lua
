local historyFilePath = nil
pcall(function()
    historyFilePath = (os.getenv("EXTERNAL_STORAGE") or "/sdcard") .. "/CSR_AI_Assistant_History.json"
end)

function loadHistory()
    if not historyFilePath then return {} end
    local ok, list = pcall(function()
        local f = io.open(historyFilePath, "r")
        if not f then return {} end
        local content = f:read("*a")
        f:close()
        if not content or content == "" then return {} end
        local decodeOk, decoded = pcall(cjson.decode, content)
        if decodeOk and type(decoded) == "table" then return decoded end
        return {}
    end)
    if ok then return list end
    return {}
end

function saveHistoryEntry(mode, resultText)
    if not historyFilePath or not resultText or resultText == "" then return end
    pcall(function()
        local history = loadHistory()
        table.insert(history, 1, {
            time = os.date("%Y-%m-%d %H:%M:%S"),
            mode = mode,
            text = resultText
        })
        while #history > CONFIG.HISTORY_MAX_ITEMS do
            table.remove(history)
        end
        local f = io.open(historyFilePath, "w")
        if f then
            f:write(cjson.encode(history))
            f:close()
        end
        logInfo("History entry saved: " .. tostring(mode))
    end)
end

function clearHistory()
    if not historyFilePath then return end
    pcall(function()
        local f = io.open(historyFilePath, "w")
        if f then f:write("[]"); f:close() end
    end)
    logInfo("History cleared by user.")
end

